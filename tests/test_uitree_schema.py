"""The contract's one table of kinds and props in C (native/moy_uitree/
moy_uitree_schema.h, generated by tools/gen_uitree_schema.py) and the check
every front makes against it (`uit_check_prop`, moy_uitree_check.c): the
header cannot drift from tests/uitree_contract/contract.json, and the check
answers the contract for every kind and prop."""
import difflib
import os
import subprocess
import sys

import pytest

import test_uitree_contract as K

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KINDS = K.TABLE["kinds"]
ANY, TEXT, INT, BOOL, LIST, DICT, FN = range(7)


@pytest.fixture(scope="module")
def m():
    import runtime  # noqa: F401  -- the flat module namespace
    import moy_uitree
    return moy_uitree


def test_the_header_is_the_contract_s():
    r = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "gen_uitree_schema.py"), "--check"],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr


def _built(k):
    return [p for p, d in KINDS[k].get("props", {}).items() if not d.get("designed")]


def test_every_built_prop_of_every_built_kind_passes(m):
    for k, d in KINDS.items():
        if d.get("designed"):
            assert m.check_prop(k, "shown", ANY, None)[0] == "N01", k
            continue
        extra = [] if k == "page" else [p for p in list(K.TABLE["common_props"]) + list(K.TABLE["child_props"])
                                        if p not in d.get("props", {})]     # a kind's own prop of that name wins
        for p in _built(k) + extra:
            assert m.check_prop(k, p, ANY, None) is None, (k, p)


def test_a_designed_prop_is_refused_as_not_built(m):
    for k, d in KINDS.items():
        for p, pd in d.get("props", {}).items():
            if pd.get("designed") and not d.get("designed"):
                code, what, _, _ = m.check_prop(k, p, ANY, None)
                assert code == "N01" and "designs it" in what, (k, p)


def test_a_retired_prop_names_its_replacement(m):
    for name, why in K.TABLE["retired"]["props"].items():
        p, _, kind = name.partition("@")
        if kind in ("action", "app"):
            continue                # an action's and the app's: not a node's prop
        kinds = [kind] if kind else list(KINDS)
        for k in kinds:
            if p in KINDS[k].get("props", {}) or KINDS[k].get("designed"):
                continue
            assert m.check_prop(k, p, ANY, None) == ("N04", "ui.%s %s= is retired" % (k, p), "", why), (k, p)


def test_a_word_prop_takes_its_words_alone(m):
    for k, d in KINDS.items():
        for p, pd in d.get("props", {}).items():
            t = pd["type"]
            if not t.startswith("word:") or pd.get("designed") or d.get("designed"):
                continue
            words = t[5:].split(",")
            assert m.prop_words(k, p) == t[5:]
            for w in words:
                assert m.check_prop(k, p, TEXT, w) is None, (k, p, w)
            assert m.check_prop(k, p, TEXT, "{wide?%s:%s}" % (words[0], words[-1])) is None
            assert m.check_prop(k, p, TEXT, "nope") == (
                "N01", "ui.%s %s='nope'" % (k, p), ", ".join(words), "%s='%s'" % (p, words[0]))


def test_a_value_of_a_class_its_type_does_not_take(m):
    assert m.check_prop("canvas", "draw", FN, None) is None
    assert m.check_prop("canvas", "draw", TEXT, "draw")[:2] == ("N01", "ui.canvas draw= is a text")
    assert m.check_prop("row", "gap", LIST, None)[0] == "T03"
    assert m.check_prop("row", "gap", INT, None) is None
    assert m.check_prop("row", "gap", TEXT, "{g}") is None
    assert m.check_prop("tabs", "offered", DICT, None) is None
    assert m.check_prop("tabs", "offered", LIST, None)[0] == "N01"
    assert m.check_prop("button", "alone", BOOL, None) is None
    assert m.check_prop("button", "alone", TEXT, "yes")[0] == "N01"
    assert m.check_prop("button", "arg", DICT, None) is None          # a literal: any value


def test_an_unknown_prop_gets_difflib_s_near_names(m):
    for k, d in KINDS.items():
        if d.get("designed"):
            continue
        names = m.check_prop(k, "zzzz", ANY, None)[2]
        names = [] if names == "(none)" else names.split(", ")
        for p in names:
            for w in (p[:-1], p + "s", "x" + p, p[::-1], p[:2] + p[3:]):
                if not w or w in names or K.TABLE["retired"]["props"].get(w):
                    continue
                code, what, expected, fix = m.check_prop(k, w, ANY, None)
                if code != "N01":
                    continue
                near = " or ".join(repr(x) for x in difflib.get_close_matches(w, names, 2, 0.6))
                assert fix == ("did you mean %s?" % near if near else
                               "drop it; %s takes %s" % (k, ", ".join(names) or "none")), (k, w)
                assert what == "ui.%s has no prop '%s'" % (k, w)


def test_the_python_front_raises_the_check_at_the_call_s_line(tmp_path):
    import uitree_check
    path = tmp_path / "wrap.py"
    path.write_text('import uitree as ui\ns = ui.state(n=0)\ndef build():\n    with ui.page("P"):\n'
                    '        ui.label("x", wrap="lines")\n        ui.label("y", ink="dim")\n')
    got = [(e.code, e.where[1], e.text()) for e in uitree_check.check(str(path)).errors]
    assert got[0][:2] == ("N01", 5) and "ui.label wrap='lines'" in got[0][2] and "fix: wrap='cut'" in got[0][2]
