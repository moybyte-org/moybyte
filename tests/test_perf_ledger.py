def fps(v):
    return pp.metric(v, "fps", pp.HIGHER, [v, v, v])


def ms(v):
    return pp.metric(v, "ms", pp.LOWER, [v, v])


def kib(v):
    return pp.metric(v, "KiB", pp.HIGHER, [v])


def rec(board, commit, date, errors=None, start=pp.AFTER_SUITE, **metrics):
    return pp.record(board, metrics, commit, tree="t", date=date, secs=1.0,
                     image={"stamp": commit, "sha256": "sha" + commit[:4]},
                     errors=errors, protocol=pp.protocol(start))


@pytest.fixture
def records(tmp_path):
    d = tmp_path / "perf"
    for r in [
        rec("tdeck", "aaaa1111", "2026-11-15T10:00:00",
            **{"Brick Siege fps": fps(50.0), "Brick Siege frame": ms(20.0),
               "Letter Blitz fps": fps(40.0), "heap sram free": kib(100.0)}),
        rec("tdeck", "bbbb2222", "2026-11-15T11:00:00",
            errors={"Sakura Lua": "not a run tile on this board's home: not measured"},
            **{"Brick Siege fps": fps(60.0), "Brick Siege frame": ms(16.0),
               "heap sram free": kib(110.0)}),
        rec("p4", "bbbb2222", "2026-11-15T11:30:00",
            **{"Brick Siege fps": fps(61.0), "window drag fps": fps(30.0)}),
    ]:
        pp.append(r, str(d / ("%s.jsonl" % r["board"])))
    return d


def write(records, tmp_path, *args):
    out = tmp_path / "ledger.md"
    assert pl.main(["--dir", str(records), "--out", str(out)] + list(args)) == 0
    return out, out.read_text()


def table(text, section, board):
    """The rows of `board`'s table in `section`, split into cells."""
    part = text.split("## " + section, 1)[1].split("\n## ", 1)[0]
    block = part.split("### %s\n" % board, 1)[1].split("\n### ", 1)[0]
    return [[c.strip() for c in line.strip("|").split("|")]
            for line in block.splitlines() if line.startswith("|")]


def test_the_file_says_it_is_generated_and_names_its_selection(records, tmp_path):
    _, text = write(records, tmp_path, "--baseline", "aaaa1111")
    lines = text.splitlines()
    assert lines[0].startswith("<!-- GENERATED by tools/perf_ledger.py")
    assert "Do not edit" in lines[0]
    assert lines[1].startswith(pl.ARGS_TAG)
    assert "--baseline aaaa1111" in lines[1] and "--boards p4,tdeck" in lines[1]
    assert "`python3 tools/perf_ledger.py --baseline aaaa1111`" in text


def test_each_board_has_a_cart_table_of_the_roster_with_fps_and_frame_ms(records, tmp_path):
    _, text = write(records, tmp_path)
    rows = table(text, "Carts", "tdeck")
    head, body = rows[0], rows[2:]
    assert len(head) == 3 and head[0] == "cart"
    assert head[1].startswith("fps<br>`bbbb2222`<br>image shabbbb<br>2026-11-15 11:00")
    assert head[2].startswith("frame ms<br>`bbbb2222`")
    assert [r[0] for r in body] == pl.roster()
    assert body[0] == ["Brick Siege", "60.0", "16.0"]


def test_a_metric_the_record_lacks_is_a_dash_never_zero(records, tmp_path):
    _, text = write(records, tmp_path)
    by = {r[0]: r for r in table(text, "Carts", "tdeck")[2:]}
    assert by["Letter Blitz"] == ["Letter Blitz", "-", "-"]
    assert by["Sakura Lua"] == ["Sakura Lua", "-", "-"]
    desk = {r[0]: r for r in table(text, "The desk", "tdeck")[2:]}
    assert desk["window drag fps"][2] == "-"
    assert desk["heap sram free"][2] == "110"


def test_the_baseline_is_the_record_at_that_commit_with_the_change(records, tmp_path):
    _, text = write(records, tmp_path, "--baseline", "aaaa1111")
    rows = table(text, "Carts", "tdeck")
    assert len(rows[0]) == 7
    assert "`aaaa1111`" in rows[0][2] and "`bbbb2222`" in rows[0][1]
    brick = rows[2]
    assert brick[1:4] == ["60.0", "50.0", "+20.0% better"]
    assert brick[4:7] == ["16.0", "20.0", "-20.0% better"]
    blitz = next(r for r in rows if r[0] == "Letter Blitz")
    assert blitz[1:4] == ["-", "40.0", "-"]


