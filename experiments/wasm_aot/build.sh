#!/usr/bin/env bash
# Build the #158 spike artifacts: core6502.wasm, both .aot variants, and the
# generated headers the device app embeds. See README.md for the results.
#
# Toolchain notes (learned on this box, 2026-07-27):
#  - clang has a wasm32 backend but Ubuntu ships no `wasm-ld`; rust-lld (from the
#    rustup toolchain) links wasm fine with `-flavor wasm`, and needs
#    LD_LIBRARY_PATH pointing at the toolchain's lib dir to find its libLLVM.
#  - `wamrc` ships PREBUILT for x86-64 in WAMR's GitHub releases -- no LLVM build.
#  - runtime and wamrc versions MUST match (AOT files carry a format version).
set -euo pipefail

WAMR_VERSION="${WAMR_VERSION:-2.4.5}"
HERE="$(cd "$(dirname "$0")" && pwd)"
cd "${HERE}"

# 1) WAMR source at the pinned tag (runtime for the device build) + prebuilt wamrc
if [ ! -d wamr ]; then
  echo "== cloning WAMR ${WAMR_VERSION}"
  git clone --depth 1 -b "WAMR-${WAMR_VERSION}" \
    https://github.com/bytecodealliance/wasm-micro-runtime.git wamr
fi
if [ ! -x wamrc_bin/wamrc ]; then
  echo "== fetching prebuilt wamrc ${WAMR_VERSION}"
  mkdir -p wamrc_bin
  curl -sSL -o /tmp/wamrc.tar.gz \
    "https://github.com/bytecodealliance/wasm-micro-runtime/releases/download/WAMR-${WAMR_VERSION}/wamrc-${WAMR_VERSION}-x86_64-ubuntu-22.04.tar.gz"
  tar xzf /tmp/wamrc.tar.gz -C wamrc_bin
fi

# 2) C core -> wasm32. -ffreestanding/-fno-builtin so no libc (and so the array
#    init loops don't lower to a memset we have nothing to link against).
TC="${HOME}/.rustup/toolchains/stable-x86_64-unknown-linux-gnu"
LLD="${TC}/lib/rustlib/x86_64-unknown-linux-gnu/bin/rust-lld"
echo "== compiling core6502.wasm"
clang --target=wasm32 -O2 -ffreestanding -fno-builtin -c -o core6502.o core6502.c
LD_LIBRARY_PATH="${TC}/lib" "${LLD}" -flavor wasm --no-entry --export-dynamic \
  -o core6502.wasm core6502.o

# 3) AOT variants. The P4 needs XIP (it has NO exec-capable heap -- see README);
#    the plain riscv32 build is kept only to demonstrate that failure mode.
echo "== compiling AOT (riscv32 ilp32f, plain + xip; and host x86_64)"
./wamrc_bin/wamrc --target=riscv32 --target-abi=ilp32f --opt-level=3 --size-level=3 \
  -o core6502_riscv32.aot core6502.wasm
./wamrc_bin/wamrc --xip --target=riscv32 --target-abi=ilp32f --opt-level=3 --size-level=3 \
  -o core6502_riscv32_xip.aot core6502.wasm
./wamrc_bin/wamrc --opt-level=3 --size-level=3 -o core6502_x64.aot core6502.wasm

# 4) Headers the device app embeds. NB the XIP blob is NOT embedded for execution
#    (flash .rodata is on the data bus and faults); it is flashed to the wasmaot
#    partition and mapped with ESP_PARTITION_MMAP_INST. The header only carries
#    its length.
echo "== generating headers"
python3 - <<'PY'
specs = [("core6502.wasm", "core6502_wasm.h", "core6502_wasm", False),
         ("core6502_riscv32.aot", "core6502_aot.h", "core6502_aot", False),
         ("core6502_riscv32_xip.aot", "core6502_aot_xip.h", "core6502_aot_xip", True)]
for src, hdr, var, is_const in specs:
    d = open(src, "rb").read()
    rows = ["    " + ", ".join("0x%02x" % b for b in d[i:i + 12]) + ","
            for i in range(0, len(d), 12)]
    guard = "CORE6502_%s_H" % var.upper()
    q = "const " if is_const else ""
    open("wasm_spike/main/" + hdr, "w").write(
        "/* generated by build.sh -- do not edit */\n#ifndef %s\n#define %s\n"
        "%sunsigned char __attribute__((aligned(16))) %s[] = {\n%s\n};\n"
        "%sunsigned int %s_len = %d;\n#endif\n"
        % (guard, guard, q, var, "\n".join(rows), q, var, len(d)))
    print("  %s (%d bytes)" % (hdr, len(d)))
PY

cat <<'EOF'

== next: host reference
   .venv/bin/python spike_host.py

== next: device (REPLACES the console firmware)
   cd wasm_spike
   source <esp-idf>/export.sh
   idf.py set-target esp32p4 && idf.py build
   python -m esptool --chip esp32p4 -p /dev/ttyACM0 -b 460800 \
     --before default_reset --after hard_reset write_flash \
     --flash_mode dio --flash_freq 80m --flash_size 32MB \
     0x2000 build/bootloader/bootloader.bin \
     0x8000 build/partition_table/partition-table.bin \
     0x10000 build/wasm_spike.bin \
     0x210000 ../core6502_riscv32_xip.aot
   cd .. && .venv/bin/python read_spike.py /dev/ttyACM0

== then RESTORE the console
   make firmware-flash-p4 PORT=/dev/ttyACM0
EOF
