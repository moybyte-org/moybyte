"""The image's font set (docs/look_2026-10.md step 3): the faces
tools/make_font.py builds, each a font file `NAME.fnt` (NAME is
FAMILY-SIZE-WEIGHT-BPP) whose licence `NAME.txt` is its family's.

A board image freezes its tier's faces as `fonts_data` (generated by
`tools/make_font.py module`, bytes in flash until a load copies one into
PSRAM); the host reads the whole set from native/moy_ui/fonts/; a target
with neither (the browser) carries none.

  names() -> (name, ...)   the faces this image carries
  file(name) -> bytes | None   NAME.fnt, or NAME.txt its family's licence
  face(name) -> bool       `name` is shaped as a face's NAME.fnt, carried or not
  icon_file(name) -> bytes | None   an icon set's file (tools/make_icons.py):
                           SET[.fill]-SIZE.fnt, system_icons.moygfx, and on
                           the host set.json; the image's are its tier's
  role_face(fam, role, desk) -> str | None   the face NAME.fnt a type role
                           draws in under a theme's `fam` (ROLES), None for
                           a role ROLES does not size on that class
"""

# The face each type role takes under a theme's look `fam` (a family of the
# set; docs/look_2026-10.md step 26a), as (size, weight, bpp) on the
# handheld's metrics and on the desk's, DESIGN.md's Type: `ui` the status,
# hint and row face, `title` a bar's page title on the handheld and a
# window's on the desk, `caption` the keycap legend and the column head, and
# `hero` the handheld home's title (`ui_draw.font("hero")`; None on the desk,
# whose home draws its title in `title`). tests/test_make_font.py holds each
# to its tier's set.
ROLES = {"ui": ((12, 500, 2), (15, 500, 4)),
         "title": ((14, 600, 4), (15, 600, 4)),
         "caption": ((11, 600, 2), (12, 600, 4)),
         "hero": ((19, 700, 4), None)}

try:
    import fonts_data as _data
except ImportError:
    _data = None

_DIR = None
_ICON_DIR = None


def _host_dir():
    global _DIR
    if _DIR is None:
        _DIR = ""
        try:
            import os.path as _p
            d = _p.join(_p.dirname(_p.dirname(_p.abspath(__file__))), "native", "moy_ui", "fonts")
            if _p.isdir(d):
                _DIR = d
        except (ImportError, NameError, AttributeError):
            pass
    return _DIR


def names():
    if _data is not None:
        return tuple(sorted(_data.FACES))
    d = _host_dir()
    if not d:
        return ()
    import os
    return tuple(sorted(f[:-4] for f in os.listdir(d) if f.endswith(".fnt")))


def file(name):
    if type(name) is not str or "/" in name:
        return None
    stem, ext = name[:-4], name[-4:]
    if ext not in (".fnt", ".txt") or stem not in names():
        return None
    if ext == ".txt":
        fam = stem.split("-")[0]
        if _data is not None:
            return _data.LICENCES.get(fam)
        stem = fam
    if _data is not None:
        return _data.FACES[stem]
    with open(_host_dir() + "/" + stem + ext, "rb") as f:
        return f.read()


def face(name):
    """Whether `name` is shaped as a face's file, FAMILY-SIZE-WEIGHT-BPP.fnt,
    whether or not this image carries it (the browser carries none)."""
    if type(name) is not str or not name.endswith(".fnt"):
        return False
    parts = name[:-4].split("-")
    if len(parts) != 4 or not parts[0].isalpha():
        return False
    for p in parts[1:]:
        if not p.isdigit():
            return False
    return True


def _icon_dir():
    global _ICON_DIR
    if _ICON_DIR is None:
        d = _host_dir()
        _ICON_DIR = d[:-len("fonts")] + "icons" if d else ""
    return _ICON_DIR


def icon_file(name):
    if type(name) is not str or "/" in name:
        return None
    if _data is not None:
        return getattr(_data, "ICONS", {}).get(name)
    d = _icon_dir()
    if not d:
        return None
    if name == "system_icons.moygfx":
        name = "pixel/" + name
    try:
        with open(d + "/" + name, "rb") as f:
            return f.read()
    except OSError:
        return None


def role_face(fam, role, desk):
    sized = ROLES.get(role)
    sized = sized[1 if desk else 0] if sized is not None else None
    if sized is None or type(fam) is not str or not fam.isalpha():
        return None
    return "%s-%d-%d-%d.fnt" % ((fam,) + sized)
