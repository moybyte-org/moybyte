"""Re-vendor dash, the shell native/moy_sh derives from, into native/moy_sh/dash.

    make vendor-dash                                  # .build/dash at the pin
    make vendor-dash DASH=/path/to/clone COMMIT=<sha>
    python3 tools/vendor_dash.py --check              # what would change

The terminal's shell is C at kernel level and derives from dash
(docs/os_2026-11/system.md section 1; BSD-3-Clause, owner 2026-11-03). Its
upstream is git.kernel.org/pub/scm/utils/dash/dash.git, pinned by commit
(UPSTREAM.md). This copies the pinned subset, applies Moybyte's changes from
native/moy_sh/patches/*.patch in name order, and runs dash's build-time
generators -- ported here to Python, so the copy needs no host build of dash's
helpers -- over the PATCHED sources:

  mktokens   token.h, token_vars.h        the parser's token table
  mkbuiltins builtins.c, builtins.h       the built-in table (builtins.def.in)
  mknodes    nodes.c, nodes.h             the parse tree (nodetypes, nodes.c.pat)
  mksyntax   syntax.c, syntax.h           the character classes
  mkinit     init.c                       the INIT/RESET/... event routines

mksignames is not ported: it is GPL (dash's COPYING says so), and the signal
names come from native/moy_sh's own table.

Files are read from the clone's GIT OBJECTS at one commit (`git show
<commit>:<path>`), never its working tree, so the stamp names exactly the bytes
that were copied. The stamp is native/moy_sh/dash_vendor.json (the commit, the
patches' hashes and a sha256 per file); tests/test_dash_vendor.py holds the
copy to it. A change to dash is a change to a patch, never an edit in the copy.
"""

