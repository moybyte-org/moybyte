# --- mktokens -------------------------------------------------------------

def mktokens(script):
    """token.h and token_vars.h from the table inside dash's mktokens."""
    m = re.search(r"<<\\!\n(.*?)\n!\n", script, re.S)
    rows = [line.split(None, 2) for line in m.group(1).split("\n") if line.strip()]
    token_h = STAMP % "mktokens" + "".join(
        "#define %s %d\n" % (name, i) for i, (name, _end, _text) in enumerate(rows))
    out = [STAMP % "mktokens",
           "/* Array indicating which tokens mark the end of a list */\n",
           "static const char tokendlist[] = {\n"]
    out += ["\t%s,\n" % end for _name, end, _text in rows]
    out.append("};\n\nstatic const char *const tokname[] = {\n")
    out += ['\t"%s",\n' % text.replace('"', '\\"') for _name, _end, text in rows]
    out.append("};\n\n")
    first = [r[0] for r in rows].index("TNOT")
    out.append("#define KWDOFFSET %d\n\nstatic const char *const parsekwd[] = {\n" % first)
    out.append(",\n".join('\t"%s"' % text.replace('"', "") for _n, _e, text in rows[first:]))
    out.append("\n};\n")
    return token_h, "".join(out)


# --- mkbuiltins -----------------------------------------------------------

def _cpp(text, defines):
    """The subset of the C preprocessor builtins.def.in uses."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    defs, stack, out = dict(defines), [], []
    for line in text.split("\n"):
        s = line.strip()
        live = all(stack)
        if s.startswith("#"):
            words = s[1:].split()
            if not words:
                continue
            d = words[0]
            if d == "ifndef":
                stack.append(words[1] not in defs)
            elif d == "ifdef":
                stack.append(words[1] in defs)
            elif d == "if":
                stack.append(bool(int(defs.get(words[1], 0))))
            elif d == "endif":
                stack.pop()
            elif d == "define" and live:
                defs.setdefault(words[1], words[2] if len(words) > 2 else 1)
            continue
        if live and s:
            out.append(s)
    return out


def mkbuiltins(defin):
    rows = []
    for line in _cpp(defin, BUILTIN_DEFINES):
        f = line.split()
        func, i = f[0], 1
        while i < len(f):
            if f[i].startswith("-"):
                rows.append((f[i + 1], f[i], func))
                i += 2
            else:
                rows.append((f[i], None, func))
                i += 1
    rows.sort(key=lambda r: r[0].encode())
    c = [STAMP % "mkbuiltins", '#include "shell.h"\n#include "builtins.h"\n\n']
    seen = []
    for line in _cpp(defin, BUILTIN_DEFINES):
        name = line.split()[0]
        if name not in seen:
            seen.append(name)
    c += ["int %s(int, char **);\n" % func for func in seen]
    c.append("\nconst struct builtincmd builtincmd[] = {\n")
    for name, opts, func in rows:
        opt = opts[1:] if opts else ""
        mask = (1 if "s" in opt else 0) + (2 if ("s" in opt or "u" in opt) else 0) \
            + (4 if "a" in opt else 0)
        c.append('\t{ "%s", %s, %d },\n' % (name, "NULL" if "n" in opt else func, mask))
    c.append("};\n")
    first = {}
    for i, (_name, _opts, func) in enumerate(rows):
        first.setdefault(func, i)
    h = [STAMP % "mkbuiltins"]
    h += ["#define %s (builtincmd + %d)\n" % (func.upper(), i)
          for func, i in sorted(first.items())]
    h.append("\n#define NUMBUILTINS %d\n" % len(rows))
    h.append("\n#define BUILTIN_SPECIAL 0x1\n#define BUILTIN_REGULAR 0x2\n"
             "#define BUILTIN_ASSIGN 0x4\n\nstruct builtincmd {\n"
             "\tconst char *name;\n\tint (*builtin)(int, char **);\n"
             "\tunsigned flags;\n};\n\nextern const struct builtincmd builtincmd[];\n")
    return "".join(c), "".join(h)


# --- mknodes --------------------------------------------------------------

def mknodes(nodetypes, pattern):
    names, nodestr, structs = [], [], []     # structs: [tag, [(name, type, decl)]]
    cur = None
    for raw in nodetypes.split("\n"):
        line = raw.split("#", 1)[0].rstrip(" \t")
        if not line:
            continue
        if line[0] in " \t":
            f = line.split(None, 2)
            name, typ = f[0], f[1]
            decl = {"nodeptr": "union node *%s", "nodelist": "struct nodelist *%s",
                    "string": "char *%s", "int": "int %s"}.get(typ)
            if decl:
                decl = decl % name
            elif typ in ("other", "temp"):
                decl = f[2].strip()
            else:
                raise SystemExit("mknodes: unknown type %s" % typ)
            cur[1].append((name, typ, decl))
        else:
            name, tag = line.split()
            names.append(name)
            for s in structs:
                if s[0] == tag:
                    break
            else:
                s = [tag, []]
                structs.append(s)
                cur = s
            nodestr.append(s)
    h = [STAMP % "mknodes"]
    h += ["#define %s %d\n" % (n, i) for i, n in enumerate(names)]
    h.append("\n\n\n")
    for tag, fields in structs:
        h.append("struct %s {\n" % tag)
        h += ["      %s;\n" % decl for _n, _t, decl in fields]
        h.append("};\n\n\n")
    h.append("union node {\n      int type;\n")
    h += ["      struct %s %s;\n" % (tag, tag) for tag, _f in structs]
    h.append("};\n\n\nstruct nodelist {\n\tstruct nodelist *next;\n\tunion node *n;\n};\n\n\n"
             "struct funcnode {\n\tint count;\n\tunion node n;\n};\n\n\n"
             "struct funcnode *copyfunc(union node *);\nvoid freefunc(struct funcnode *);\n")

    def func(calcsize):
        o = ["      if (n == NULL)\n", "\t    return;\n" if calcsize else "\t    return NULL;\n"]
        if calcsize:
            o.append("      funcblocksize += nodesize[n->type];\n")
        else:
            o.append("      new = funcblock;\n"
                     "      funcblock = (char *) funcblock + nodesize[n->type];\n")
        o.append("      switch (n->type) {\n")
        for s in structs:
            tag, fields = s
            o += ["      case %s:\n" % names[i] for i in range(len(names)) if nodestr[i] is s]
            for name, typ, _decl in reversed(fields[1:]):
                ref = "n->%s.%s" % (tag, name)
                if typ == "nodeptr":
                    o.append("\t    calcsize(%s);\n" % ref if calcsize else
                             "\t    new->%s.%s = copynode(%s);\n" % (tag, name, ref))
                elif typ == "nodelist":
                    o.append("\t    sizenodelist(%s);\n" % ref if calcsize else
                             "\t    new->%s.%s = copynodelist(%s);\n" % (tag, name, ref))
                elif typ == "string":
                    o.append("\t    funcstringsize += strlen(%s) + 1;\n" % ref if calcsize else
                             "\t    new->%s.%s = nodesavestr(%s);\n" % (tag, name, ref))
                elif typ in ("int", "other") and not calcsize:
                    o.append("\t    new->%s.%s = %s;\n" % (tag, name, ref))
            o.append("\t    break;\n")
        o.append("      };\n")
        if not calcsize:
            o.append("      new->type = n->type;\n")
        return o

    c = [STAMP % "mknodes"]
    for line in pattern.splitlines(True):
        s = line.strip(" \t")
        if s == "%SIZES\n":
            c.append("static const short nodesize[%d] = {\n" % len(names))
            c += ["      SHELL_ALIGN(sizeof (struct %s)),\n" % s[0] for s in nodestr]
            c.append("};\n")
        elif s == "%CALCSIZE\n":
            c += func(True)
        elif s == "%COPY\n":
            c += func(False)
        else:
            c.append(line)
    return "".join(c), "".join(h)


# --- mksyntax -------------------------------------------------------------

SYNCLASS = [
    ("CWORD", "character is nothing special"), ("CNL", "newline character"),
    ("CBACK", "a backslash character"), ("CSQUOTE", "single quote"),
    ("CDQUOTE", "double quote"), ("CENDQUOTE", "a terminating quote"),
    ("CBQUOTE", "backwards single quote"), ("CVAR", "a dollar sign"),
    ("CENDVAR", "a '}' character"), ("CLP", "a left paren in arithmetic"),
    ("CRP", "a right paren in arithmetic"), ("CEOF", "end of file"),
    ("CCTL", "like CWORD, except it must be escaped"),
    ("CSPCL", "these terminate a word"),
]
IS_ENTRY = [("ISDIGIT", "a digit"), ("ISUPPER", "an upper case letter"),
            ("ISLOWER", "a lower case letter"), ("ISUNDER", "an underscore"),
            ("ISSPECL", "the name of a special parameter")]
TYPE_MACROS = (
    "#define is_digit(c)\t((unsigned)((c) - '0') <= 9)\n"
    "#define is_alpha(c)\tisalpha((unsigned char)(c))\n"
    "#define is_name(c)\t((c) == '_' || isalpha((unsigned char)(c)))\n"
    "#define is_in_name(c)\t((c) == '_' || isalnum((unsigned char)(c)))\n"
    "#define is_special(c)\t((is_type+SYNBASE)[(signed char)(c)] & (ISSPECL|ISDIGIT))\n"
    "#define digit_val(c)\t((c) - '0')\n")


def mksyntax(parser_h):
    ctl_first = int(re.search(r"#define CTL_FIRST (-?\d+)", parser_h).group(1))
    ctl_last = int(re.search(r"#define\s+CTL_LAST (-?\d+)", parser_h).group(1))
    h = [STAMP % "mksyntax", "#include <ctype.h>\n\n#ifdef CEOF\n#undef CEOF\n#endif\n\n",
         "/* Syntax classes */\n"]
    h += ["#define %s %d\t/* %s */\n" % (n, i, c) for i, (n, c) in enumerate(SYNCLASS)]
    h.append("\n/* Syntax classes for is_ functions */\n")
    h += ["#define %s 0%o\t/* %s */\n" % (n, 1 << i, c) for i, (n, c) in enumerate(IS_ENTRY)]
    h.append("\n#define SYNBASE 129\n#define PEOF -129\n\n\n"
             "#define BASESYNTAX (basesyntax + SYNBASE)\n#define DQSYNTAX (dqsyntax + SYNBASE)\n"
             "#define SQSYNTAX (sqsyntax + SYNBASE)\n#define ARISYNTAX (arisyntax + SYNBASE)\n\n")
    h.append(TYPE_MACROS + "\n")
    c = [STAMP % "mksyntax", '#include "shell.h"\n#include "syntax.h"\n\n']
    table = []

    def fill(v):
        table[:] = [v] * 257

    def init():
        fill("CWORD")
        table[0] = "CEOF"
        for ctl in range(ctl_first, ctl_last + 1):
            table[129 + ctl] = "CCTL"

    def add(chars, cls):
        for ch in chars:
            table[ord(ch) + 129] = cls

    def emit(name, comment):
        h.append("extern const char %s[];\n" % name)
        if comment:
            c.append("\n/* %s */\n" % comment)
        c.append("const char %s[] = {\n" % name)
        c.append(",\n".join("      " + ", ".join(table[i:i + 4]) for i in range(0, 257, 4)))
        c.append("\n};\n")

    init()
    add("\n", "CNL"); add("\\", "CBACK"); add("'", "CSQUOTE"); add('"', "CDQUOTE")
    add("`", "CBQUOTE"); add("$", "CVAR"); add("}", "CENDVAR"); add("<>();&| \t", "CSPCL")
    emit("basesyntax", "syntax table used when not in quotes")
    init()
    add("\n", "CNL"); add("\\", "CBACK"); add('"', "CENDQUOTE"); add("`", "CBQUOTE")
    add("$", "CVAR"); add("}", "CENDVAR"); add("^!*?[=~:/-]", "CCTL")
    emit("dqsyntax", "syntax table used when in double quotes")
    init()
    add("\n", "CNL"); add("'", "CENDQUOTE"); add("^!*?[=~:/-]\\", "CCTL")
    emit("sqsyntax", "syntax table used when in single quotes")
    init()
    add("\n", "CNL"); add("\\", "CBACK"); add("`", "CBQUOTE"); add("$", "CVAR")
    add("}", "CENDVAR"); add("(", "CLP"); add(")", "CRP")
    emit("arisyntax", "syntax table used when in arithmetic")
    fill("0")
    add("0123456789", "ISDIGIT")
    add("abcdefghijklmnopqrstucvwxyz", "ISLOWER")
    add("ABCDEFGHIJKLMNOPQRSTUCVWXYZ", "ISUPPER")
    add("_", "ISUNDER")
    add("#?$!-*@", "ISSPECL")
    emit("is_type", "character classification table")
    return "".join(c), "".join(h)


# --- mkinit ---------------------------------------------------------------

EVENTS = [("INIT", "init", "", "Initialization code."),
          ("EXITRESET", "exitreset", "", "This routine is called when an error or an interrupt occurs in an\n * interactive shell and control is returned to the main command loop\n * but prior to exitshell."),
          ("FORKRESET", "forkreset", "union node *n", "This routine is called when we enter a subshell."),
          ("POSTEXITRESET", "postexitreset", "", "This routine is called after exitreset."),
          ("RESET", "reset", "", "This routine is called when an error or an interrupt occurs in an\n * interactive shell and control is returned to the main command loop.")]


def _match(name, line):
    return line.startswith(name) and line[len(name):len(name) + 1] in ("{", " ", "\t", "\n")


def _gooddefine(line):
    if not _match("#define", line):
        return False
    m = re.match(r"#define[ \t]*([^ \t]*)", line)
    if "(" in m.group(1):
        return False
    return not line.rstrip("\n").endswith("\\")


def mkinit(sources):
    # system.h first: its moy_sh_posix.h names every file call the shell's own
    headers = ['"system.h"', '"shell.h"', '"mystring.h"', '"init.h"']
    defines, decls = [], []
    code = {name: [] for name, _r, _a, _c in EVENTS}
    for fname, text in sources:
        lines = text.splitlines(True)
        i, amiddecls = 0, False
        while i < len(lines):
            line = lines[i]
            i += 1
            for name, _r, _a, _c in EVENTS:
                if _match(name, line):
                    body = ["\n      /* from %s: */\n" % fname, "      {\n"]
                    while lines[i] != "}\n":
                        l2 = lines[i]
                        i += 1
                        p = l2.lstrip("\t")
                        indent = 6 + 8 * (len(l2) - len(p))
                        q = p.lstrip(" ")
                        indent += len(p) - len(q)
                        if q.startswith("\n") or q.startswith("#"):
                            indent = 0
                        body.append("\t" * (indent // 8) + " " * (indent % 8) + q)
                    i += 1
                    body.append("      }\n")
                    code[name] += body
                    break
            if _match("INCLUDE", line):
                m = re.search(r'["<][^ \t\n]*[">]', line)
                if m.group(0) not in headers:
                    headers.append(m.group(0))
            if _match("MKINIT", line):
                if line == "MKINIT\n":
                    decls.append("\n")
                    while True:
                        l2 = lines[i]
                        i += 1
                        decls.append(l2)
                        if l2.startswith("}"):
                            break
                    amiddecls = False
                else:
                    if not amiddecls:
                        decls.append("\n")
                    rest = line[6:]
                    m = re.match(r"([^=/\n]*)(.*)", rest, re.S)
                    head, tail = m.group(1), m.group(2)
                    if tail.startswith("="):
                        semi = tail.find(";")
                        tail = tail[semi:] if semi >= 0 else tail
                        head = head.rstrip(" ")
                    decls.append("extern" + head + tail)
                    amiddecls = True
            if line.startswith("#") and _gooddefine(line):
                name = re.match(r"#define[ \t]*([^ \t\n]*)", line).group(1)
                defines.append("#undef %s\n" % name)
                defines.append(line)
    out = [STAMP % "mkinit"]
    out += ["#include %s\n" % h for h in headers]
    out.append("\n\n\n")
    out += defines
    out.append("\n\n")
    out += decls
    for name, routine, args, comment in EVENTS:
        out.append("\n\n\n/*\n * %s\n */\n\nvoid\n%s(%s) {\n" % (comment, routine, args))
        out += code[name]
        out.append("}\n")
    return "".join(out)


# --- the copy ---------------------------------------------------------------

def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def sha256_file(path):
    with open(path, "rb") as f:
        return sha256_bytes(f.read())


def git(clone, *args, binary=False):
    out = subprocess.check_output(("git", "-C", clone) + args, stderr=subprocess.DEVNULL)
    return out if binary else out.decode().strip()


def dest_rel(upstream_rel):
    """Where an upstream path lands under native/moy_sh/dash."""
    return upstream_rel[4:] if upstream_rel.startswith("src/") else upstream_rel


def patch_files():
    if not os.path.isdir(PATCHES):
        return []
    return sorted(os.path.join(PATCHES, n) for n in os.listdir(PATCHES) if n.endswith(".patch"))


def vendored_paths():
    """Every file this script owns under native/moy_sh/dash, repo-relative."""
    rels = [dest_rel(r) for r in FILES] + GENERATED
    return sorted(os.path.relpath(os.path.join(DEST, r), ROOT).replace(os.sep, "/") for r in rels)


def build(clone, commit):
    """{dest rel: bytes} for the copy: upstream at `commit`, patched, generated."""
    work = tempfile.mkdtemp(prefix="vendor_dash_")
    try:
        for rel in FILES:
            data = git(clone, "show", "%s:%s" % (commit, rel), binary=True)
            path = os.path.join(work, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as f:
                f.write(data)
        for patch in patch_files():
            r = subprocess.run(["git", "apply", "--whitespace=nowarn", "-p1", patch],
                               cwd=work, capture_output=True, text=True)
            if r.returncode:
                raise SystemExit("vendor-dash: %s does not apply:\n%s"
                                 % (os.path.relpath(patch, ROOT), r.stderr))
        out = {}
        for rel in FILES:
            with open(os.path.join(work, rel), "rb") as f:
                out[dest_rel(rel)] = f.read()
        src = lambda n: out[n].decode()
        token_h, token_vars = mktokens(src("mktokens"))
        builtins_c, builtins_h = mkbuiltins(src("builtins.def.in"))
        nodes_c, nodes_h = mknodes(src("nodetypes"), src("nodes.c.pat"))
        syntax_c, syntax_h = mksyntax(src("parser.h"))
        init_c = mkinit([(n, src(n)) for n in INIT_SOURCES])
        for name, text in (("token.h", token_h), ("token_vars.h", token_vars),
                           ("builtins.c", builtins_c), ("builtins.h", builtins_h),
                           ("nodes.c", nodes_c), ("nodes.h", nodes_h),
                           ("syntax.c", syntax_c), ("syntax.h", syntax_h),
                           ("init.c", init_c)):
            out[name] = text.encode()
        return out
    finally:
        shutil.rmtree(work, ignore_errors=True)


def pin_header(commit):
    return ("/* GENERATED by tools/vendor_dash.py -- the dash commit the copy in\n"
            " * dash/ was made from (dash_vendor.json). Do not edit. */\n"
            "#ifndef MOY_SH_DASH_PIN_H\n#define MOY_SH_DASH_PIN_H\n"
            "#define MOY_SH_DASH_COMMIT \"%s\"\n#endif\n" % commit)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dash", default=os.environ.get("MOYBYTE_DASH", DEFAULT_CLONE),
                    help="a clone of %s (default: .build/dash)" % UPSTREAM)
    ap.add_argument("--commit", default=PIN, help="the commit to vendor (default: the pin)")
    ap.add_argument("--check", action="store_true", help="report what would change; write nothing")
    args = ap.parse_args(argv)

    if not os.path.isdir(os.path.join(args.dash, ".git")):
        print("vendor-dash: no clone at %s\n  git clone %s %s" % (args.dash, UPSTREAM, args.dash),
              file=sys.stderr)
        return 2
    try:
        commit = git(args.dash, "rev-parse", "--verify", args.commit + "^{commit}")
    except Exception:
        print("vendor-dash: %s is not a commit in %s" % (args.commit, args.dash), file=sys.stderr)
        return 2
    date = git(args.dash, "log", "-1", "--format=%cs", commit)
    print("vendor-dash: %s @ %s" % (args.dash, commit[:12]))
    copy = build(args.dash, commit)

    changed, files = [], {}
    for rel, data in sorted(copy.items()):
        dst = os.path.join(DEST, rel)
        files[os.path.relpath(dst, ROOT).replace(os.sep, "/")] = sha256_bytes(data)
        if os.path.isfile(dst) and sha256_file(dst) == sha256_bytes(data):
            continue
        changed.append(os.path.relpath(dst, ROOT))
        if not args.check:
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(dst, "wb") as f:
                f.write(data)
    for dirpath, _dirs, names in os.walk(DEST):
        for name in names:
            rel = os.path.relpath(os.path.join(dirpath, name), ROOT).replace(os.sep, "/")
            if rel not in files:
                changed.append(rel + " (removed)")
                if not args.check:
                    os.remove(os.path.join(ROOT, rel))
    header = pin_header(commit)
    if not os.path.isfile(PIN_HEADER) or open(PIN_HEADER).read() != header:
        changed.append(os.path.relpath(PIN_HEADER, ROOT))
        if not args.check:
            with open(PIN_HEADER, "w", newline="\n") as f:
                f.write(header)
    patches = {os.path.relpath(p, ROOT).replace(os.sep, "/"): sha256_file(p) for p in patch_files()}
    for path in changed:
        print("  %s %s" % ("would update" if args.check else "updated", path))
    if not changed:
        print("  already up to date")
    if args.check:
        stamp = json.load(open(MANIFEST)) if os.path.isfile(MANIFEST) else {}
        return 1 if changed or stamp.get("patches") != patches else 0
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        json.dump({"upstream": {"repo": UPSTREAM, "commit": commit, "date": date},
                   "patches": patches, "files": files}, f, indent=2, sort_keys=True)
        f.write("\n")
    print("  stamped %s" % os.path.relpath(MANIFEST, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
