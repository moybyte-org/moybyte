#!/usr/bin/env python3
"""docs/perf/image.md, written whole from the board builds' image records.

    python3 tools/image_ledger.py              each board's latest record
    python3 tools/image_ledger.py --check      fail when the file differs from
                                               what its records give
    python3 tools/image_ledger.py record BOARD_DIR BUILD_DIR APP_BIN
                                               what every board's build runs
                                               after its size guard

THE RECORDS. Each board build (tools/esp32_build_lib.sh, after the size guard)
reads its link map and its ELF and appends one record to
`~/.cache/moybyte-image/<board>.jsonl` (MOYBYTE_IMAGE_DIR moves the directory):
the app image's bytes, the slot it must fit (the board's own partition CSV),
the headroom floor (board.toml `[image] headroom_floor_kib`), the flash map,
and the image's bytes by part. The records are this machine's, so the ledger
is committed when someone chooses to, never by the build; the build prints
the command.

WHAT A PART IS. The bytes an image carries are its loaded sections: the ELF's
allocated PROGBITS sections, the flash-mapped text and rodata and the
initialised RAM the bootloader copies. The link map attributes each input
section to the object that brought it, and each object falls in one part by its
path (`PARTS`, first match wins): the baked browser console
(native/moy_web's generated table), the frozen Python console, our C (each
module under `native/`, named), MicroPython, the radios' stacks, mbedTLS, the C
library and the rest of ESP-IDF. The linker merges every object's C string
literals into one section and names the first object as its owner, so they are
a part of their own. What the image file holds beyond its sections (segment
headers, alignment, the checksum and hash) is `image format`.

THE SELECTION. Per board, the latest record (or the latest at or before
`--until`). The file's second line names each board's record by its date, so
`--check` regenerates exactly that file and new records do not turn it red.
`--check` skips, exit 0, where a board it names has no records on this machine
(CI has none).
"""

from __future__ import annotations

import argparse
import datetime
import difflib
import json
import os
import re
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import board_config  # noqa: E402

FORMAT = 1
LEDGER = os.path.join(ROOT, "docs", "perf", "image.md")
GENERATED = ("<!-- GENERATED by tools/image_ledger.py from board build records. "
             "Do not edit it: regenerate it. -->")
ARGS_TAG = "<!-- image_ledger:"

RADIO_LIBS = (
    "net80211", "pp", "phy", "coexist", "core", "mesh", "espnow", "smartconfig",
    "wapi", "wpa_supplicant", "lwip", "bt", "btdm_app", "btbb", "ble_app",
    "esp_wifi", "esp_phy", "esp_coex", "esp_hosted", "esp_wifi_remote",
    "esp_netif", "mdns", "dhcpserver",
)
TOOLCHAIN_LIBS = ("c", "c_nano", "m", "m_nano", "gcc", "stdc++", "g", "gcov",
                  "supc++", "nosys")

# (part, test on the object path) in order; the first match names the part.
PARTS = (
    ("browser console (baked)", lambda p: _obj(p) == "moy_web_blob.gen.c.obj"),
    ("frozen Python console", lambda p: _obj(p) == "frozen_content.c.obj"),
    ("our C", lambda p: "/native/" in p or (_lib(p) or "").startswith("moy_")),
    ("MicroPython", lambda p: "esp-idf/main/libmain.a" in p
     or "/micropython/" in p and "esp-idf/" not in p),
    ("radios: Wi-Fi, BT, lwIP", lambda p: _lib(p) in RADIO_LIBS),
    ("mbedTLS", lambda p: (_lib(p) or "").startswith(("mbed", "p256m", "everest"))),
    ("C library, compiler runtime", lambda p: _lib(p) in TOOLCHAIN_LIBS),
    ("ESP-IDF, the rest", lambda p: "esp-idf/" in p or "/esp-idf/" in p),
)
STRINGS = "C string literals (merged)"
FILL = "linker fill"
OVERHEAD = "image format"
OTHER = "other"
PART_ORDER = [p for p, _ in PARTS] + [STRINGS, FILL, OTHER, OVERHEAD]
TOP_NATIVE = 12


def _obj(path):
    """The object's file name: an archive member's, or the path's last part."""
    m = re.search(r"\(([^()]+)\)$", path)
    return m.group(1) if m else os.path.basename(path)


def _lib(path):
    """`foo` of a path inside `libfoo.a` (a managed component's
    `espressif__foo` too), else None."""
    m = re.search(r"/lib([^/()]+)\.a(\(|$)", "/" + path)
    return m.group(1).replace("espressif__", "") if m else None


def native_module(path):
    """Our C module an object belongs to (`moy_ui`, `moy_wasm`), else None."""
    m = re.search(r"/native/(?:\.staged/)?([^/]+)/", path)
    if m:
        return m.group(1)
    lib = _lib(path) or ""
    if lib == "moy_wamr":
        return "moy_wasm"
    if lib.startswith("moy_"):
        return lib[:-5] if lib.endswith("_core") else lib
    return None


def part_of(path):
    for name, test in PARTS:
        if test(path):
            return name
    return OTHER


# -- the ELF and the map --------------------------------------------------------

def loaded_sections(elf_path):
    """{name: size} of the ELF's allocated PROGBITS sections: what an app image
    carries (ELF32, little-endian: both the S3's Xtensa and the P4's RISC-V)."""
    with open(elf_path, "rb") as f:
        data = f.read()
    if data[:4] != b"\x7fELF" or data[4] != 1 or data[5] != 1:
        raise ValueError("%s: not a little-endian ELF32" % elf_path)
    shoff, = struct.unpack_from("<I", data, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", data, 0x2E)
    heads = [struct.unpack_from("<IIIIIIIIII", data, shoff + i * shentsize)
             for i in range(shnum)]
    strtab = heads[shstrndx][4]

    def name(off):
        end = data.index(b"\0", strtab + off)
        return data[strtab + off:end].decode()

    out = {}
    for sh_name, sh_type, flags, _addr, _off, size, *_ in heads:
        if sh_type == 1 and flags & 2 and size:
            out[name(sh_name)] = size
    return out


_HEX = r"0x([0-9a-fA-F]+)"
_OUT = re.compile(r"^(\.\S+)(?:\s+%s\s+%s)?" % (_HEX, _HEX))
_IN = re.compile(r"^ (\.\S+|\*fill\*|COMMON)(?:\s+%s\s+%s(?:\s+(\S.*))?)?\s*$"
                 % (_HEX, _HEX))
_CONT = re.compile(r"^\s+%s\s+%s(?:\s+(\S.*))?\s*$" % (_HEX, _HEX))


def map_inputs(map_path, keep):
    """Yield (output section, input section, address, bytes, object path) for
    every input section of the output sections in `keep`, from a GNU ld link
    map. A `*fill*` has no object (None)."""
    current = None
    pending = None
    started = False
    with open(map_path, errors="replace") as f:
        for line in f:
            if not started:
                started = line.startswith("Linker script and memory map")
                continue
            line = line.rstrip("\n")
            if pending is not None:
                m = _CONT.match(line)
                name, pending = pending, None
                if m:
                    if current in keep:
                        yield (current, name, int(m.group(1), 16),
                               int(m.group(2), 16), m.group(3))
                    continue
            if line.startswith("."):
                m = _OUT.match(line)
                current = m.group(1) if m else None
                continue
            if current not in keep:
                continue
            m = _IN.match(line)
            if not m:
                continue
            sec, addr, size, obj = m.groups()
            if size is None:
                pending = sec
                continue
            yield current, sec, int(addr, 16), int(size, 16), obj


def _spans(entries):
    """Each input's bytes in its output section, from the addresses: the
    linker lists every merged string section at its pre-merge size, several at
    one address, so a size is clipped at the next address and one address is
    counted once."""
    entries = sorted(entries, key=lambda e: e[0])
    for i, (addr, size, sec, obj) in enumerate(entries):
        if not size:
            continue
        nxt = next((e[0] for e in entries[i + 1:] if e[0] > addr), None)
        if i and entries[i - 1][0] == addr and entries[i - 1][1]:
            continue
        yield sec, obj, size if nxt is None else min(size, nxt - addr)


def breakdown(map_path, elf_path, image_bytes):
    """{"parts": {part: bytes}, "native": {module: bytes}, "loaded": bytes}."""
    keep = loaded_sections(elf_path)
    by_out = {}
    for out, sec, addr, size, obj in map_inputs(map_path, keep):
        by_out.setdefault(out, []).append((addr, size, sec, obj))
    parts = dict.fromkeys(PART_ORDER, 0)
    native = {}
    for entries in by_out.values():
        for sec, obj, size in _spans(entries):
            if sec == "*fill*" or obj is None:
                parts[FILL] += size
            elif ".str1." in sec:
                parts[STRINGS] += size
            else:
                part = part_of(obj)
                parts[part] += size
                if part == "our C":
                    mod = native_module(obj) or "?"
                    native[mod] = native.get(mod, 0) + size
    loaded = sum(keep.values())
    # What no map line attributes (a section the linker makes) is fill too.
    parts[FILL] += loaded - sum(parts.values())
    parts[OVERHEAD] = image_bytes - loaded
    return {"parts": {k: v for k, v in parts.items() if v},
            "native": dict(sorted(native.items(), key=lambda kv: -kv[1])),
            "loaded": loaded}


# -- the board's flash -------------------------------------------------------------

def flash_bytes(board_dir):
    for s in board_config.sdkconfig_settings(board_dir):
        m = re.fullmatch(r"CONFIG_ESPTOOLPY_FLASHSIZE_(\d+)MB", s.option)
        if m and s.value == "y":
            return int(m.group(1)) << 20
    return None


def partition_csv(board_dir):
    found = []
    for dirpath, _dirs, files in os.walk(os.path.join(board_dir, "boards")):
        found += [os.path.join(dirpath, f) for f in files
                  if f.startswith("partitions-") and f.endswith(".csv")]
    if len(found) != 1:
        raise ValueError("%s: want one boards/*/partitions-*.csv, found %d"
                         % (board_dir, len(found)))
    return found[0]


def partitions(board_dir):
    """[(name, type, subtype, offset, size)] in table order, the unlisted tail
    (the store mainline MicroPython builds over the rest of the chip) last as
    `vfs (tail)`."""
    rows = []
    with open(partition_csv(board_dir)) as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            cells = [c.strip() for c in line.split(",")]
            rows.append((cells[0], cells[1], cells[2], int(cells[3], 0),
                         int(cells[4], 0)))
    total = flash_bytes(board_dir)
    end = max(off + size for _n, _t, _s, off, size in rows)
    if total and end < total and not any(r[0] == "vfs" for r in rows):
        rows.append(("vfs (tail)", "data", "littlefs", end, total - end))
    return rows


def slot_bytes(rows):
    for name, _t, _s, _off, size in rows:
        if name == "ota_0":
            return size
    raise ValueError("no ota_0 in the partition table")


# -- records -------------------------------------------------------------------------

def history_dir():
    return os.environ.get("MOYBYTE_IMAGE_DIR") or os.path.join(
        os.path.expanduser("~"), ".cache", "moybyte-image")


def git_head(root=ROOT):
    try:
        head = subprocess.run(["git", "-C", root, "rev-parse", "--short=8", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "?"
    dirty = subprocess.run(["git", "-C", root, "diff", "--quiet", "HEAD", "--"],
                           capture_output=True).returncode != 0
    return head + ("+" if dirty else "")


def make_record(board_dir, build_dir, app_bin, date=None, commit=None):
    ota, floor = board_config.headroom_floor(board_dir)
    rows = partitions(board_dir)
    image = os.path.getsize(app_bin)
    got = breakdown(os.path.join(build_dir, "micropython.map"),
                    os.path.join(build_dir, "micropython.elf"), image)
    return {
        "format": FORMAT,
        "board": ota,
        "date": date or datetime.datetime.now().isoformat(timespec="seconds"),
        "commit": commit or git_head(),
        "flash": flash_bytes(board_dir),
        "slot": slot_bytes(rows),
        "image": image,
        "floor": floor,
        "partitions": [list(r) for r in rows],
        **got,
    }


def append(rec, directory=None):
    directory = directory or history_dir()
    os.makedirs(directory, exist_ok=True)
    with open(os.path.join(directory, "%s.jsonl" % rec["board"]), "a") as f:
        f.write(json.dumps(rec, sort_keys=True) + "\n")


def records(board, directory):
    path = os.path.join(directory, "%s.jsonl" % board)
    out = []
    try:
        with open(path) as f:
            for line in f:
                line = line.strip()
                if line:
                    rec = json.loads(line)
                    if rec.get("format") == FORMAT:
                        out.append(rec)
    except OSError:
        pass
    return out


def boards_in(directory):
    try:
        names = sorted(n[:-6] for n in os.listdir(directory) if n.endswith(".jsonl"))
    except OSError:
        return []
    return [b for b in names if records(b, directory)]


def select(directory, boards=None, until=None, dates=None):
    """[(board, record)], each board's latest at or before `until`, or the one
    of the date `dates[board]` names."""
    picked = []
    for b in boards or boards_in(directory):
        recs = records(b, directory)
        if dates and b in dates:
            recs = [r for r in recs if r["date"] == dates[b]]
        elif until:
            recs = [r for r in recs if r["date"] <= until]
        if recs:
            picked.append((b, recs[-1]))
    return picked


# -- the ledger -------------------------------------------------------------------------

def _b(n):
    return "{:,}".format(n)


def _kib(n):
    return "{:,} KiB".format(n // 1024) if n % 1024 == 0 else "{:,.1f} KiB".format(n / 1024)


def _pct(n, d):
    return "%.1f%%" % (100.0 * n / d) if d else "-"


def _row(cells):
    return "| " + " | ".join(str(c) for c in cells) + " |"


def _table(head, rows, right=()):
    align = ["---:" if i in right else "---" for i in range(len(head))]
    return "\n".join([_row(head), _row(align)] + [_row(r) for r in rows])


def headroom(rec):
    return rec["slot"] - rec["image"]


def _store(rec):
    for name, _t, _s, _off, size in rec["partitions"]:
        if name.startswith("vfs"):
            return size
    return None


def _web_part(rec):
    for name, _t, _s, _off, size in rec["partitions"]:
        if name == "web":
            return size
    return None


def summary(picked):
    rows = []
    for b, r in picked:
        p = r["parts"]
        store = _store(r)
        web = p.get("browser console (baked)")
        rows.append([
            "`%s`" % b,
            "%d MiB" % (r["flash"] >> 20) if r["flash"] else "-",
            _b(r["slot"]), _b(r["image"]),
            "%s (%s)" % (_b(headroom(r)), _pct(headroom(r), r["slot"])),
            _kib(r["floor"]) if r["floor"] else "0",
            _b(web) if web else ("own partition" if _web_part(r) else "-"),
            _b(p.get("frozen Python console", 0)),
            _kib(store) if store else "none",
        ])
    return _table(["board", "flash", "slot (B)", "image (B)", "headroom (B)",
                   "floor", "browser console in the image (B)",
                   "frozen Python (B)", "internal store"], rows,
                  right=range(2, 9))


def board_section(b, r):
    out = ["## %s" % b, "",
           "Built from `%s` on %s. Slot %s B, image %s B, headroom %s B (%s), "
           "floor %s." % (r["commit"], r["date"].replace("T", " ")[:16],
                          _b(r["slot"]), _b(r["image"]), _b(headroom(r)),
                          _pct(headroom(r), r["slot"]),
                          _kib(r["floor"]) if r["floor"] else "0"),
           ""]
    parts = sorted(r["parts"].items(),
                   key=lambda kv: (kv[0] == OVERHEAD, -kv[1]))
    out.append(_table(["part", "bytes", "of the image"],
                      [[n, _b(v), _pct(v, r["image"])] for n, v in parts],
                      right=(1, 2)))
    native = sorted(r.get("native", {}).items(), key=lambda kv: (-kv[1], kv[0]))
    if native:
        top = native[:TOP_NATIVE]
        rest = sum(v for _n, v in native[TOP_NATIVE:])
        rows = [["`%s`" % n, _b(v)] for n, v in top]
        if rest:
            rows.append(["%d more" % (len(native) - TOP_NATIVE), _b(rest)])
        out += ["", "Our C by module (`native/`):", "",
                _table(["module", "bytes"], rows, right=(1,))]
    flash = [[n, "%s/%s" % (t, s), "0x%X" % off, "0x%X" % size, _b(size)]
             for n, t, s, off, size in r["partitions"]]
    out += ["", "The flash (the board's partition CSV):", "",
            _table(["partition", "type", "offset", "size", "bytes"], flash,
                   right=(4,))]
    return "\n".join(out)


def args_line(picked):
    return "%s --boards %s -->" % (ARGS_TAG, ",".join(
        "%s@%s" % (b, r["date"]) for b, r in picked))


def render(picked):
    out = [GENERATED, args_line(picked), "",
           "# Image ledger", "",
           "GENERATED by `tools/image_ledger.py` from the records every board "
           "build appends (its docstring says how a part is counted). Do not "
           "edit it: regenerate it with `python3 tools/image_ledger.py` after "
           "the builds and commit the result.",
           "",
           "The slot is the board's `ota_0`; the image must fit it and keep the "
           "board's headroom floor (`[image] headroom_floor_kib` in its "
           "board.toml), or the build fails (`moybyte_app_size_guard`, "
           "`tools/esp32_build_lib.sh`). Bytes are the app image's: every part "
           "below is in it once per slot.",
           "", summary(picked), ""]
    for b, r in picked:
        out += [board_section(b, r), ""]
    return "\n".join(out)


def file_dates(path):
    try:
        with open(path) as f:
            head = [next(f, "") for _ in range(3)]
    except OSError:
        return None
    for line in head:
        if line.startswith(ARGS_TAG):
            words = line[len(ARGS_TAG):].replace("-->", "").split()
            if words[:1] == ["--boards"] and len(words) > 1:
                return dict(w.split("@", 1) for w in words[1].split(","))
            return {}
    return None


def check(path, directory):
    dates = file_dates(path)
    if dates is None:
        print("image_ledger: %s names no selection; regenerate it" % path)
        return 1
    have = boards_in(directory)
    missing = [b for b in dates if b not in have]
    if missing:
        print("image_ledger: no records for %s on this machine; check skipped"
              % ", ".join(missing))
        return 0
    picked = select(directory, list(dates), dates=dates)
    if len(picked) != len(dates):
        gone = sorted(set(dates) - {b for b, _ in picked})
        print("image_ledger: the records %s names for %s are gone; check skipped"
              % (path, ", ".join(gone)))
        return 0
    want = render(picked)
    with open(path) as f:
        now = f.read()
    if now == want:
        print("image_ledger: %s is what its records generate" % path)
        return 0
    diff = list(difflib.unified_diff(now.splitlines(), want.splitlines(),
                                     "committed", "generated", lineterm="", n=0))
    print("image_ledger: %s differs from what its records generate "
          "(hand-edited, or the records changed):" % path)
    print("\n".join(diff[:40]))
    return 1


def record_main(argv):
    ap = argparse.ArgumentParser(prog="image_ledger.py record")
    ap.add_argument("board_dir")
    ap.add_argument("build_dir", help="the port's build directory (its "
                    "micropython.map and micropython.elf)")
    ap.add_argument("app_bin")
    ap.add_argument("--dir", help=argparse.SUPPRESS)
    a = ap.parse_args(argv)
    rec = make_record(a.board_dir, a.build_dir, a.app_bin)
    append(rec, a.dir)
    p = rec["parts"]
    print("Image ledger: %s %s B -- browser console %s, frozen Python %s, our C "
          "%s; `python3 tools/image_ledger.py` writes docs/perf/image.md"
          % (rec["board"], _b(rec["image"]),
             _b(p.get("browser console (baked)", 0)),
             _b(p.get("frozen Python console", 0)), _b(p.get("our C", 0))))
    return 0


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if argv[:1] == ["record"]:
        return record_main(argv[1:])
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--boards", help="comma-separated board ids (default: every "
                    "board with records)")
    ap.add_argument("--until", metavar="DATE",
                    help="take records at or before this ISO date")
    ap.add_argument("--check", action="store_true",
                    help="fail when the file differs from what its records give")
    ap.add_argument("--out", default=LEDGER, help=argparse.SUPPRESS)
    ap.add_argument("--dir", help=argparse.SUPPRESS)
    a = ap.parse_args(argv)
    directory = a.dir or history_dir()
    if a.check:
        return check(a.out, directory)
    boards = [b for b in (a.boards or "").split(",") if b] or None
    picked = select(directory, boards, a.until)
    if not picked:
        print("image_ledger: no image records in %s" % directory)
        return 2
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as f:
        f.write(render(picked))
    print("image_ledger: wrote %s (%s)" % (
        a.out, ", ".join("%s %s" % (b, r["commit"]) for b, r in picked)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
