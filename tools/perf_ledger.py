#!/usr/bin/env python3
"""docs/perf/ledger.md, written whole from the board pass's perf records.

    python3 tools/perf_ledger.py                      each board's latest
                                                      after-suite record
    python3 tools/perf_ledger.py --baseline 5789c851  ...beside its record at
                                                      that commit, change in %
    python3 tools/perf_ledger.py --protocol fresh     perf-baseline's records
    python3 tools/perf_ledger.py --check              fail when the file differs
                                                      from what its records give

THE RECORDS are the ones tools/perf_pass.py appends, after each board's suite in
`tools/board.py pass` and on its own as `tools/board.py perf-baseline`
(`~/.cache/moybyte-perf/<board>.jsonl`; MOYBYTE_PERF_DIR moves the directory).
They are this machine's, so the ledger is committed when someone chooses to,
never by the pass; the pass prints the command.

THE SELECTION. One protocol (`--protocol`, perf_pass's docstring: `after-suite`
the board pass's stage, the default, or `fresh` perf-baseline's on a just-booted
board), and of it only the #66 roster's runs: a board measures differently
after a suite than after a boot, so the ledger never sets one beside the other.
Per board, the latest record of that protocol at or before `--until` (default:
the newest such record of all) and, with `--baseline`, the latest record of it
at or before that whose commit matches that prefix; a board whose records at
the baseline commit are all of another protocol says so and has no baseline
column. A record of unknown protocol (perf_pass.infer_protocol) is never
selected. The file's second line names the selection it was written from
(protocol, baseline, until, boards), so `--check`
regenerates exactly that file and new records do not turn it red. `--check`
skips, exit 0, where the records are absent (CI has none) or a board it names
has none on this machine.

THE TABLES. Per board, the carts (the roster `tools/p4_perf.py` runs, then any
other cart a record carries): drawn fps and frame ms. Then the desk: idle,
collector, heap and window drag. A metric a record does not hold is `-`, never
0; a change past the metric's noise band is marked as perf_pass's block marks
it. Each record's errors and conditions are notes under its board's table.
"""

from __future__ import annotations

import argparse
import ast
import difflib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import perf_pass  # noqa: E402

LEDGER = os.path.join(ROOT, "docs", "perf", "ledger.md")
GENERATED = ("<!-- GENERATED by tools/perf_ledger.py from perf_pass records. "
             "Do not edit it: regenerate it. -->")
ARGS_TAG = "<!-- perf_ledger:"
DESK_PREFIXES = ("desk idle", "heap ", "window drag")
SUFFIXES = (" fps", " frame")


def roster():
    """tools/p4_perf.py's DEFAULT_ROSTER, read from its source (importing the
    tool loads the console), then the compiled cart's label."""
    with open(os.path.join(HERE, "p4_perf.py")) as f:
        tree = ast.parse(f.read())
    for node in tree.body:
        if (isinstance(node, ast.Assign)
                and any(getattr(t, "id", None) == "DEFAULT_ROSTER" for t in node.targets)):
            names = list(ast.literal_eval(node.value))
            break
    else:
        names = []
    return names + ["%s uncapped" % perf_pass.COMPILED]


# -- the selection -------------------------------------------------------------


def boards_in(directory):
    try:
        names = os.listdir(directory)
    except OSError:
        return None
    return sorted(n[:-len(".jsonl")] for n in names if n.endswith(".jsonl"))


def records(board, directory, until=None, protocol=None):
    """`board`'s records by date, at or before `until`; with `protocol`, only
    the #66 roster's runs under it."""
    recs = perf_pass.history(board, os.path.join(directory, "%s.jsonl" % board))
    recs = sorted(recs, key=lambda r: r.get("date", ""))
    if until:
        recs = [r for r in recs if r.get("date", "") <= until]
    if protocol:
        want = perf_pass.protocol_key(perf_pass.protocol(protocol))
        recs = [r for r in recs
                if perf_pass.protocol_key(r.get("protocol")) == want]
    return recs


def _same_commit(a, b):
    a, b = a.rstrip("+"), b.rstrip("+")
    return bool(a) and bool(b) and (a.startswith(b) or b.startswith(a))


def at_commit(recs, commit):
    for r in reversed(recs):
        if _same_commit(r.get("commit", ""), commit):
            return r
    return None


def select(directory, boards=None, baseline=None, until=None,
           protocol=perf_pass.AFTER_SUITE):
    """[(board, latest, baseline record or None)] of one protocol and the
    `until` that names the latest records."""
    boards = boards or boards_in(directory) or []
    picked = []
    for b in boards:
        recs = records(b, directory, until, protocol)
        if not recs:
            continue
        picked.append((b, recs[-1], at_commit(recs, baseline) if baseline else None))
    if until is None and picked:
        until = max(p[1].get("date", "") for p in picked)
    return picked, until


# -- the tables ----------------------------------------------------------------


def _is_desk(name):
    return name.startswith(DESK_PREFIXES)


def _cart(name):
    for s in SUFFIXES:
        if name.endswith(s):
            return name[:-len(s)]
    return None


def carts(picked):
    """The roster, then any other cart a selected record carries, in order."""
    out = roster()
    for _, latest, base in picked:
        for rec in (latest, base):
            for name in (rec or {}).get("metrics", {}):
                c = _cart(name)
                if c and not _is_desk(name) and c not in out:
                    out.append(c)
    return out


def desk_metrics(picked):
    out = []
    for _, latest, base in picked:
        for rec in (latest, base):
            for name in (rec or {}).get("metrics", {}):
                if _is_desk(name) and name not in out:
                    out.append(name)
    return out


def header(what, rec):
    image = rec.get("image") or {}
    return "%s<br>`%s`<br>image %s<br>%s" % (
        what, rec.get("commit", "?"), image.get("sha256") or "?",
        rec.get("date", "?").replace("T", " ")[:16])


def _changes(latest, base):
    """{metric name: change cell} from perf_pass.compare."""
    out = {}
    for name, _m, _pv, change, _band, flag in perf_pass.compare(latest, base):
        if change is not None:
            cell = "%+.1f%%" % change if round(change, 1) else "0.0%"
            out[name] = cell + (" " + flag if flag else "")
    return out


def _value(rec, name):
    m = (rec or {}).get("metrics", {}).get(name)
    if m is None:
        return "-"
    return perf_pass._num(m.get("value"), m.get("unit"))


def _row(cells):
    return "| " + " | ".join(cells) + " |"


def _table(head, rows):
    lines = [_row(head), _row(["---"] + ["---:"] * (len(head) - 1))]
    lines += [_row(r) for r in rows]
    return lines


def cart_table(latest, base, names):
    changes = _changes(latest, base) if base else {}
    head = ["cart"]
    for what in ("fps", "frame ms"):
        head.append(header(what, latest))
        if base:
            head += [header(what, base), "change"]
    rows = []
    for c in names:
        row = [c]
        for suffix in SUFFIXES:
            name = c + suffix
            row.append(_value(latest, name))
            if base:
                row += [_value(base, name), changes.get(name, "-")]
        rows.append(row)
    return _table(head, rows)


def desk_table(latest, base, names):
    changes = _changes(latest, base) if base else {}
    head = ["metric", "unit", header("value", latest)]
    if base:
        head += [header("value", base), "change"]
    rows = []
    for name in names:
        unit = next(((r or {}).get("metrics", {}).get(name, {}).get("unit")
                     for r in (latest, base)
                     if name in (r or {}).get("metrics", {})), "")
        row = [name, unit, _value(latest, name)]
        if base:
            row += [_value(base, name), changes.get(name, "-")]
        rows.append(row)
    return _table(head, rows)


def notes(latest, base, baseline, desk, others=()):
    """The records' errors and conditions, as a list under the table;
    `others` the protocols of the board's records at the baseline commit when
    none is the ledger's."""
    out = []
    pairs = [("latest", latest)] + ([("baseline", base)] if base else [])
    for label, rec in pairs:
        errors = rec.get("errors") or {}
        for name in sorted(errors):
            if _is_desk(name) == desk:
                out.append("- %s `%s`: %s: %s" % (label, rec.get("commit", "?"),
                                                   name, errors[name]))
        held = (rec.get("conditions") or {}).get("wifi_held")
        if held and not desk:
            out.append("- %s `%s`: WiFi held by %s while it measured"
                       % (label, rec.get("commit", "?"), ", ".join(held)))
    if baseline and base is None and others:
        out.append("- no %s record at commit `%s` on this board; its records "
                   "there are %s, not compared"
                   % (perf_pass.protocol_key(latest.get("protocol"))[0], baseline,
                      ", ".join(others)))
    elif baseline and base is None:
        out.append("- no record at commit `%s` on this board" % baseline)
    return out


def other_protocols(directory, board, baseline, until):
    """The protocol names of `board`'s records at the baseline commit."""
    out = []
    for r in records(board, directory, until):
        name = perf_pass.protocol_name(r.get("protocol"))
        if _same_commit(r.get("commit", ""), baseline) and name not in out:
            out.append(name)
    return out


def args_line(baseline, until, boards, protocol=perf_pass.AFTER_SUITE):
    parts = ["--protocol", protocol]
    if baseline:
        parts += ["--baseline", baseline]
    parts += ["--until", until or "", "--boards", ",".join(boards)]
    return "%s %s -->" % (ARGS_TAG, " ".join(parts))


def command(baseline, protocol=perf_pass.AFTER_SUITE):
    return "python3 tools/perf_ledger.py" + (
        " --protocol %s" % protocol if protocol != perf_pass.AFTER_SUITE else "") + (
        " --baseline %s" % baseline if baseline else "")


PROTOCOL_TEXT = {
    perf_pass.AFTER_SUITE: "after its on-glass suite: the board pass's stage, "
                           "15-20 minutes of tests into the boot",
    perf_pass.FRESH: "freshly booted, nothing run since: `tools/board.py "
                     "perf-baseline`",
}


def render(picked, until, baseline=None, protocol=perf_pass.AFTER_SUITE,
           others=None):
    """The ledger. `others`: {board: the protocols of its records at the
    baseline commit} for a board with no baseline record of `protocol`."""
    want = perf_pass.protocol(protocol)
    for board, latest, base in picked:
        for r in (latest, base):
            if r is not None and not perf_pass.same_protocol(r, {"protocol": want}):
                raise ValueError("%s: a %s record in a %s ledger" % (
                    board, perf_pass.protocol_name(r.get("protocol")), protocol))
    others = others or {}
    boards = [p[0] for p in picked]
    cart_names = carts(picked)
    desk_names = desk_metrics(picked)
    out = [
        GENERATED,
        args_line(baseline, until, boards, protocol),
        "",
        "# Performance ledger",
        "",
        "GENERATED by `tools/perf_ledger.py` from the perf records "
        "`tools/perf_pass.py` keeps, the board pass's stage and "
        "`tools/board.py perf-baseline` alike. Do not edit it: regenerate it with "
        "`%s` and commit the result." % command(baseline, protocol),
        "",
        "Every number here was taken **%s**: %s. A board measures differently "
        "after a suite than after a boot (internal SRAM, and a cart behind "
        "the carts before it), so a ledger holds one protocol and never sets "
        "the other beside it (`--protocol`)." % (protocol, PROTOCOL_TEXT[protocol]),
        "",
        "How each number is taken is `tools/perf_pass.py`'s docstring. The "
        "levers that moved them, and the ones that did not, are "
        "`docs/perf/levers.md`. The story behind a number (a bisect, an A/B) "
        "is a comment on its issue: #66 for the carts, #58 for the desk.",
        "",
        "Each column names the commit its image was built from, the image's "
        "sha256 and the date of the run. `-` is a number the run did not "
        "take, never 0; a change past the metric's noise band says `better` "
        "or `WORSE`.",
        "",
        "## Carts (#66)",
        "",
        "fps: frames drawn a second, PERF DIAG off. frame ms: the loop's work "
        "behind one drawn frame, under PERF DIAG.",
    ]
    for board, latest, base in picked:
        out += ["", "### %s" % board, ""]
        out += cart_table(latest, base, cart_names)
        n = notes(latest, base, baseline, desk=False, others=others.get(board, ()))
        if n:
            out += [""] + n
    out += ["", "## The desk (#58)", "",
            "The desk at rest (drawn fps, the loop's work a frame, the "
            "collector's stops), the heap there, and a window dragged on a "
            "windowed tier."]
    for board, latest, base in picked:
        out += ["", "### %s" % board, ""]
        out += desk_table(latest, base, desk_names)
        n = notes(latest, base, baseline, desk=True, others=others.get(board, ()))
        if n:
            out += [""] + n
    return "\n".join(out) + "\n"


# -- the command line ----------------------------------------------------------


def file_args(path):
    """(baseline, until, boards, protocol) from the file's selection line, or
    None."""
    try:
        with open(path) as f:
            head = [next(f, "") for _ in range(3)]
    except OSError:
        return None
    for line in head:
        if line.startswith(ARGS_TAG):
            words = line[len(ARGS_TAG):].replace("-->", "").split()
            got = {"--baseline": None, "--until": None, "--boards": "",
                   "--protocol": perf_pass.AFTER_SUITE}
            for k, v in zip(words[::2], words[1::2]):
                got[k] = v
            return (got["--baseline"], got["--until"],
                    [b for b in got["--boards"].split(",") if b], got["--protocol"])
    return None


def regen_command(path=LEDGER, protocol=None):
    """The command that rewrites the committed ledger at its own baseline,
    from its own protocol or `protocol`."""
    got = file_args(path)
    return command(got[0] if got else None,
                   protocol or (got[3] if got else perf_pass.AFTER_SUITE))


def build(directory, boards, baseline, until, protocol):
    """(picked, until, others): the selection and the notes of the boards
    whose baseline commit holds only other protocols."""
    picked, until = select(directory, boards, baseline, until, protocol)
    others = {}
    if baseline:
        for b, _latest, base in picked:
            if base is None:
                others[b] = other_protocols(directory, b, baseline, until)
    return picked, until, others


def check(path, directory):
    got = file_args(path)
    if got is None:
        print("perf_ledger: %s names no selection; regenerate it" % path)
        return 1
    baseline, until, boards, protocol = got
    if protocol not in perf_pass.STARTS:
        print("perf_ledger: %s names protocol %r; regenerate it" % (path, protocol))
        return 1
    have = boards_in(directory)
    if have is None:
        print("perf_ledger: no perf records here (%s); check skipped" % directory)
        return 0
    missing = [b for b in boards if b not in have]
    if missing:
        print("perf_ledger: no records for %s on this machine; check skipped"
              % ", ".join(missing))
        return 0
    picked, until, others = build(directory, boards, baseline, until, protocol)
    want = render(picked, until, baseline, protocol, others)
    with open(path) as f:
        now = f.read()
    if now == want:
        print("perf_ledger: %s is what its records generate" % path)
        return 0
    diff = list(difflib.unified_diff(now.splitlines(), want.splitlines(),
                                     "committed", "generated", lineterm="", n=0))
    print("perf_ledger: %s differs from what its records generate "
          "(hand-edited, or the records changed):" % path)
    print("\n".join(diff[:40]))
    return 1


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--protocol", choices=perf_pass.STARTS,
                    default=perf_pass.AFTER_SUITE,
                    help="the one protocol the ledger is written from "
                         "(default: after-suite, the board pass's)")
    ap.add_argument("--baseline", metavar="COMMIT",
                    help="the commit each board's latest record is set beside")
    ap.add_argument("--until", metavar="DATE",
                    help="take records at or before this ISO date")
    ap.add_argument("--boards", help="comma-separated board ids (default: every "
                    "board with records)")
    ap.add_argument("--check", action="store_true",
                    help="fail when the file differs from what its records give")
    ap.add_argument("--out", default=LEDGER, help=argparse.SUPPRESS)
    ap.add_argument("--dir", help=argparse.SUPPRESS)
    a = ap.parse_args(argv)
    directory = a.dir or perf_pass.history_dir()
    if a.check:
        return check(a.out, directory)
    boards = [b for b in (a.boards or "").split(",") if b] or None
    picked, until, others = build(directory, boards, a.baseline, a.until,
                                  a.protocol)
    if not picked:
        print("perf_ledger: no %s perf records in %s" % (a.protocol, directory))
        return 2
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as f:
        f.write(render(picked, until, a.baseline, a.protocol, others))
    print("perf_ledger: wrote %s, %s (%s)" % (
        a.out, a.protocol,
        ", ".join("%s %s" % (b, r.get("commit", "?")) for b, r, _ in picked)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
