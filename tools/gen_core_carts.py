#!/usr/bin/env python3
"""Write native/moy_store/moy_core.h, the C store's copy of the core carts
(runtime/carts/moy_seed.py's CORE) and the built-ins' namespace
(runtime/carts/moy_store_base.py's BUILTIN_NS), from that one source. The
removal record (native/moy_store/moy_removed.c) reads it;
tests/test_official_carts.py fails a header that differs from what this
writes.

    tools/gen_core_carts.py           write the header
    tools/gen_core_carts.py --check   exit 1 when the header differs
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from runtime.moy_store_base import BUILTIN_NS  # noqa: E402
from tools.board_config import core_carts  # noqa: E402

HEADER = os.path.join(ROOT, "native", "moy_store", "moy_core.h")


def render():
    ids = core_carts()
    rows = "".join(' \\\n    "%s",' % cid for cid in ids)
    return ("// GENERATED by tools/gen_core_carts.py from runtime/carts/moy_seed.py's CORE\n"
            "// and moy_store_base.py's BUILTIN_NS: do not edit; run tools/gen_core_carts.py.\n"
            "#ifndef MOY_CORE_H\n"
            "#define MOY_CORE_H\n"
            "\n"
            "// The built-ins' namespace: a seed cart's id is \"%s.<slug>\".\n"
            "#define MOY_BUILTIN_NS \"%s\"\n"
            "\n"
            "// The core carts' ids, the initializer of a const char *const array.\n"
            "#define MOY_CORE_COUNT %d\n"
            "#define MOY_CORE_IDS%s\n"
            "\n"
            "#endif // MOY_CORE_H\n") % (BUILTIN_NS, BUILTIN_NS, len(ids), rows)


def main(argv):
    text = render()
    if "--check" in argv:
        with open(HEADER, encoding="utf-8") as f:
            if f.read() != text:
                print("%s is stale: run tools/gen_core_carts.py" % HEADER, file=sys.stderr)
                return 1
        return 0
    with open(HEADER, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
