#!/usr/bin/env python3
"""Write the toolkit's tables from their data (docs/kernel_toolkit_2026-10.md
§2.1): native/moy_ui's `style.json` in, its `moy_ui_tables.h` and
`moy_ui_tables.c` out; native/moy_spine's `strings/en.json` in, its
`moy_str_table.h` and `moy_str_table.c` out. The output is committed: no build
runs this, and tests/test_ui_tables.py regenerates it and fails on any
difference.

    python3 tools/gen_ui_tables.py [--dir native/moy_ui] [--str-dir native/moy_spine] [--check]
"""

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, "native", "moy_ui")
STR_DIR = os.path.join(ROOT, "native", "moy_spine")


def _c_str(s):
    out = []
    for ch in s.encode("utf-8"):
        c = chr(ch)
        if c in '"\\':
            out.append("\\" + c)
        elif 32 <= ch < 127:
            out.append(c)
        else:
            out.append("\\%03o" % ch)
    return '"' + "".join(out) + '"'


def _ident(name):
    return re.sub(r"[^A-Z0-9]", "_", name.upper())


class Tables:
    def __init__(self, style):
        self.style = style
        self.tokens = list(style["tokens"])
        self.aliases = list(style["aliases"])
        self.roles = self.tokens + self.aliases
        self.states = list(style["states"])
        ckinds = list(style["kinds"])
        mkinds = [k for k in style["metrics"] if k not in ckinds]
        self.kinds = ckinds + mkinds
        self.skins = list(style["skin_order"])
        self.specs = [()]                    # spec 0: paint nothing
        self.spec_ix = {(): 0}

    def role(self, name):
        if name not in self.roles:
            raise SystemExit("style.json: %r is no token and no alias" % name)
        return self.roles.index(name)

    def term(self, s):
        if isinstance(s, bool) or not isinstance(s, (int, str)):
            raise SystemExit("style.json: a chain holds %r" % (s,))
        if isinstance(s, int):
            if not 0 <= s < 64:
                raise SystemExit("style.json: palette index %d" % s)
            return s
        return -1 - self.role(s)

    def spec(self, s):
        if s is None:
            terms = ()
        elif isinstance(s, list):
            terms = tuple(self.term(x) for x in s)
        else:
            terms = (self.term(s),)
        if len(terms) > 3:
            raise SystemExit("style.json: a chain longer than 3: %r" % (s,))
        if terms not in self.spec_ix:
            self.spec_ix[terms] = len(self.specs)
            self.specs.append(terms)
        return self.spec_ix[terms]

    def kind_specs(self, skin):
        delta = self.style["skins"][skin].get("kinds", {})
        rows = []
        for k in self.kinds:
            states = delta.get(k, self.style["kinds"].get(k))
            row = []
            for st in self.states:
                triple = None if states is None else states.get(st)
                if triple is None:
                    row.append(None)
                else:
                    row.append(tuple(self.spec(x) for x in triple))
            rows.append(row)
        return rows

    def metrics(self, skin):
        delta = self.style["skins"][skin].get("metrics", {})
        out = []
        for k in self.kinds:
            slots = delta.get(k, self.style["metrics"].get(k))
            base = self.style["metrics"].get(k)
            if slots is not None and list(slots) != list(base):
                raise SystemExit("skin %s renames %s's slots" % (skin, k))
            out.append(None if slots is None else list(slots.values()))
        return out


def generate(style):
    t = Tables(style)
    nslot = max(len(v) for v in style["metrics"].values())
    skins = [(s, t.kind_specs(s), t.metrics(s)) for s in t.skins]
    h = []
    h.append("// GENERATED by tools/gen_ui_tables.py from style.json.")
    h.append("// Do not edit: change the data and regenerate "
             "(tests/test_ui_tables.py).")
    h.append("#ifndef MOY_UI_TABLES_H\n#define MOY_UI_TABLES_H\n")
    h.append("#include <stdint.h>\n")
    h.append("#define MOY_UI_TOKENS %d" % len(t.tokens))
    h.append("#define MOY_UI_ROLES %d" % len(t.roles))
    h.append("#define MOY_UI_STATES %d" % len(t.states))
    h.append("#define MOY_UI_KINDS %d" % len(t.kinds))
    h.append("#define MOY_UI_COLOR_KINDS %d" % len(style["kinds"]))
    h.append("#define MOY_UI_SLOTS %d" % nslot)
    h.append("#define MOY_UI_SKINS %d" % len(t.skins))
    h.append("#define MOY_UI_SPECS %d" % len(t.specs))
    h.append("#define MOY_UI_HITS_CAP %d" % style["hits_capacity"])
    h.append("#define MOY_UI_GLYPHS %d" % len(style["glyphs"]))
    h.append("#define MOY_UI_GLYPH_SIZE %d" % style["glyph_size"])
    h.append("")
    h.append("// The states, strongest first (widget_state's precedence).")
    h.append("enum {")
    for i, st in enumerate(t.states):
        h.append("    MOY_UI_%s = %d," % (_ident(st), i))
    h.append("};\n")
    h.append("// The kinds: those a style entry colours, then those with only "
             "metrics.")
    h.append("enum {")
    for i, k in enumerate(t.kinds):
        h.append("    MOY_UI_K_%s = %d," % (_ident(k), i))
    h.append("};\n")
    h.append("// Each kind's metric slots.")
    h.append("enum {")
    for k, slots in style["metrics"].items():
        for i, s in enumerate(slots):
            h.append("    MOY_UI_M_%s_%s = %d," % (_ident(k), _ident(s), i))
    h.append("};\n")
    h.append("typedef struct { int8_t n; int8_t t[3]; } moy_ui_spec_t;")
    h.append("extern const int moy_ui_n_tokens, moy_ui_n_roles, moy_ui_n_states, "
             "moy_ui_n_kinds,")
    h.append("    moy_ui_n_color_kinds, moy_ui_n_skins, moy_ui_n_glyphs;")
    h.append("extern const int moy_ui_hits_cap;")
    h.append("extern const char *const moy_ui_token_names[MOY_UI_TOKENS];")
    h.append("extern const char *const moy_ui_role_names[MOY_UI_ROLES];")
    h.append("extern const int8_t moy_ui_alias[MOY_UI_ROLES - MOY_UI_TOKENS][3];")
    h.append("extern const char *const moy_ui_state_names[MOY_UI_STATES];")
    h.append("extern const char *const moy_ui_kind_names[MOY_UI_KINDS];")
    h.append("extern const char *const moy_ui_skin_names[MOY_UI_SKINS];")
    h.append("extern const char *const moy_ui_button_kinds[%d][2];"
             % len(style["button_kinds"]))
    h.append("#define MOY_UI_BUTTON_KINDS %d" % len(style["button_kinds"]))
    h.append("extern const moy_ui_spec_t moy_ui_specs[MOY_UI_SPECS];")
    h.append("// [skin][kind][state][field, ink, edge]: a spec index, or 0xff "
             "where the kind names no such state.")
    h.append("extern const uint8_t moy_ui_kind_specs[MOY_UI_SKINS][MOY_UI_KINDS]"
             "[MOY_UI_STATES][3];")
    h.append("// [skin][kind]: the slot count (0: no metrics), then the values.")
    h.append("extern const uint8_t moy_ui_metric_n[MOY_UI_KINDS];")
    h.append("extern const int16_t moy_ui_metric_vals[MOY_UI_SKINS][MOY_UI_KINDS]"
             "[MOY_UI_SLOTS];")
    h.append("extern const char *const moy_ui_metric_slots[MOY_UI_KINDS];")
    h.append("// The glyph vocabulary: each glyph's rows, bit (size - 1 - col) the ink.")
    h.append("extern const char *const moy_ui_glyph_names[MOY_UI_GLYPHS];")
    h.append("extern const uint16_t moy_ui_glyph_rows[MOY_UI_GLYPHS][MOY_UI_GLYPH_SIZE];")
    h.append("\n#endif // MOY_UI_TABLES_H")

    if len(t.specs) >= 255:
        raise SystemExit("more than 255 distinct token specs")
    c = []
    c.append("// GENERATED by tools/gen_ui_tables.py from style.json.")
    c.append("// Do not edit: change the data and regenerate "
             "(tests/test_ui_tables.py).\n")
    c.append('#include "moy_ui_tables.h"\n')
    c.append("// The counts, for a binding that reads the tables by symbol.")
    for k in ("tokens", "roles", "states", "kinds", "color_kinds", "skins",
              "glyphs"):
        c.append("const int moy_ui_n_%s = MOY_UI_%s;" % (k, k.upper()))
    c.append("const int moy_ui_hits_cap = MOY_UI_HITS_CAP;")
    c.append("")

    def names(decl, seq):
        c.append("%s = {" % decl)
        for s in seq:
            c.append("    %s," % _c_str(s))
        c.append("};\n")

    names("const char *const moy_ui_token_names[MOY_UI_TOKENS]", t.tokens)
    names("const char *const moy_ui_role_names[MOY_UI_ROLES]", t.roles)
    c.append("const int8_t moy_ui_alias[MOY_UI_ROLES - MOY_UI_TOKENS][3] = {")
    for a in t.aliases:
        chain = [t.tokens.index(x) for x in style["aliases"][a]]
        if len(chain) > 3 or any(x not in t.tokens for x in style["aliases"][a]):
            raise SystemExit("alias %s: a chain of tokens, at most 3" % a)
        chain += [-1] * (3 - len(chain))
        c.append("    {%s},  // %s" % (", ".join(map(str, chain)), a))
    c.append("};\n")
    names("const char *const moy_ui_state_names[MOY_UI_STATES]", t.states)
    names("const char *const moy_ui_kind_names[MOY_UI_KINDS]", t.kinds)
    names("const char *const moy_ui_skin_names[MOY_UI_SKINS]", t.skins)
    c.append("const char *const moy_ui_button_kinds[%d][2] = {"
             % len(style["button_kinds"]))
    for k, v in style["button_kinds"].items():
        c.append("    {%s, %s}," % (_c_str(k), _c_str(v)))
    c.append("};\n")
    c.append("const moy_ui_spec_t moy_ui_specs[MOY_UI_SPECS] = {")
    for terms in t.specs:
        pad = list(terms) + [0] * (3 - len(terms))
        c.append("    {%d, {%s}}," % (len(terms), ", ".join(map(str, pad))))
    c.append("};\n")
    c.append("const uint8_t moy_ui_kind_specs[MOY_UI_SKINS][MOY_UI_KINDS]"
             "[MOY_UI_STATES][3] = {")
    for s, rows, _m in skins:
        c.append("    {  // %s" % s)
        for k, row in zip(t.kinds, rows):
            cells = ", ".join("{0xff, 0xff, 0xff}" if tr is None else
                              "{%d, %d, %d}" % tr for tr in row)
            c.append("        {%s},  // %s" % (cells, k))
        c.append("    },")
    c.append("};\n")
    c.append("const uint8_t moy_ui_metric_n[MOY_UI_KINDS] = {%s};\n" % ", ".join(
        str(len(style["metrics"].get(k, {}))) for k in t.kinds))
    c.append("const int16_t moy_ui_metric_vals[MOY_UI_SKINS][MOY_UI_KINDS]"
             "[MOY_UI_SLOTS] = {")
    for s, _rows, mets in skins:
        c.append("    {  // %s" % s)
        for k, vals in zip(t.kinds, mets):
            v = (vals or []) + [0] * (nslot - len(vals or []))
            c.append("        {%s},  // %s" % (", ".join(map(str, v)), k))
        c.append("    },")
    c.append("};\n")
    names("const char *const moy_ui_metric_slots[MOY_UI_KINDS]",
          [" ".join(style["metrics"].get(k, {})) for k in t.kinds])
    gs = style["glyph_size"]
    if gs > 16:
        raise SystemExit("a glyph row is a uint16: glyph_size %d" % gs)
    names("const char *const moy_ui_glyph_names[MOY_UI_GLYPHS]", list(style["glyphs"]))
    c.append("const uint16_t moy_ui_glyph_rows[MOY_UI_GLYPHS][MOY_UI_GLYPH_SIZE] = {")
    for k, rows in style["glyphs"].items():
        if len(rows) != gs or any(len(r) != gs or set(r) - set("#.") for r in rows):
            raise SystemExit("glyph %s: %d rows of %d '#'/'.'" % (k, gs, gs))
        vals = [sum(1 << (gs - 1 - i) for i, ch in enumerate(r) if ch == "#")
                for r in rows]
        c.append("    {%s},  // %s" % (", ".join("0x%03X" % v for v in vals), k))
    c.append("};\n")
    return "\n".join(h) + "\n", "\n".join(c)


def generate_strings(strings):
    """moy_str_table.h/.c: the ids, their names and English."""
    ids = list(strings)
    for sid, text in strings.items():
        if not re.match(r"^[a-z_]+\.[a-z_]+$", sid):
            raise SystemExit("%s: a string id is section.name" % sid)
        bad = [m for m in re.findall(r"%(?:08x|.)", text.replace("%%", ""))
               if m not in ("%s", "%d", "%u", "%08x")]
        if bad:
            raise SystemExit("%s: a conversion outside %%s %%d %%u %%08x" % sid)
    head = ("// GENERATED by tools/gen_ui_tables.py from strings/en.json.\n"
            "// Do not edit: change the data and regenerate "
            "(tests/test_ui_tables.py).\n")
    h = [head, "#ifndef MOY_STR_TABLE_H\n#define MOY_STR_TABLE_H\n",
         "#define MOY_STRINGS %d\n" % len(ids), "// The string ids.", "enum {"]
    for i, sid in enumerate(ids):
        h.append("    MOY_S_%s = %d," % (_ident(sid), i))
    h.append("};\n")
    h.append("extern const char *const moy_str_ids[MOY_STRINGS];")
    h.append("extern const char *const moy_str_en[MOY_STRINGS];")
    h.append("\n#endif // MOY_STR_TABLE_H")
    c = [head, '#include "moy_str_table.h"\n']
    for decl, seq in (("moy_str_ids", ids), ("moy_str_en", [strings[i] for i in ids])):
        c.append("const char *const %s[MOY_STRINGS] = {" % decl)
        for s in seq:
            c.append("    %s," % _c_str(s))
        c.append("};\n")
    return "\n".join(h) + "\n", "\n".join(c)


def load(d):
    with open(os.path.join(d, "style.json")) as f:
        return json.load(f)


def load_strings(d):
    with open(os.path.join(d, "strings", "en.json")) as f:
        return json.load(f)["strings"]


def outputs(ui_dir=DIR, str_dir=STR_DIR):
    """[(path, text)] of every generated file."""
    h, c = generate(load(ui_dir))
    sh, sc = generate_strings(load_strings(str_dir))
    return [(os.path.join(ui_dir, "moy_ui_tables.h"), h),
            (os.path.join(ui_dir, "moy_ui_tables.c"), c),
            (os.path.join(str_dir, "moy_str_table.h"), sh),
            (os.path.join(str_dir, "moy_str_table.c"), sc)]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dir", default=DIR)
    ap.add_argument("--str-dir", default=STR_DIR)
    ap.add_argument("--check", action="store_true",
                    help="fail when the committed tables differ")
    a = ap.parse_args(argv)
    out = outputs(a.dir, a.str_dir)
    if a.check:
        for p, text in out:
            if not os.path.exists(p) or open(p).read() != text:
                print("%s is stale: run tools/gen_ui_tables.py" % p)
                return 1
        return 0
    for p, text in out:
        with open(p, "w") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
