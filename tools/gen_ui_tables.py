#!/usr/bin/env python3
"""Write the toolkit's tables from their data (docs/kernel_toolkit_2026-10.md
§2.1): native/moy_ui's `style.json` in, its `moy_ui_tables.h` and
`moy_ui_tables.c` out, the seed theme packages (`themes/*.json`) embedded in
them; native/moy_spine's `strings/en.json` in, its
`moy_str_table.h` and `moy_str_table.c` out. The output is committed: no build
runs this, and tests/test_ui_tables.py regenerates it and fails on any
difference.

    python3 tools/gen_ui_tables.py [--dir native/moy_ui] [--str-dir native/moy_spine] [--check]
"""

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, "native", "moy_ui")
STR_DIR = os.path.join(ROOT, "native", "moy_spine")


def _c_str(s):
    out = []
    for ch in s.encode("utf-8"):
        c = chr(ch)
        if c in '"\\':
            out.append("\\" + c)
        elif 32 <= ch < 127:
            out.append(c)
        else:
            out.append("\\%03o" % ch)
    return '"' + "".join(out) + '"'


def _ident(name):
    return re.sub(r"[^A-Z0-9]", "_", name.upper())


class Tables:
    def __init__(self, style):
        self.style = style
        self.tokens = list(style["tokens"])
        self.aliases = list(style["aliases"])
        self.roles = self.tokens + self.aliases
        self.states = list(style["states"])
        ckinds = list(style["kinds"])
        mkinds = [k for k in style["metrics"] if k not in ckinds]
        self.kinds = ckinds + mkinds
        self.specs = [()]                    # spec 0: paint nothing
        self.spec_ix = {(): 0}

    def role(self, name):
        if name not in self.roles:
            raise SystemExit("style.json: %r is no token and no alias" % name)
        return self.roles.index(name)

    def term(self, s):
        if isinstance(s, bool) or not isinstance(s, (int, str)):
            raise SystemExit("style.json: a chain holds %r" % (s,))
        if isinstance(s, int):
            if not 0 <= s < 64:
                raise SystemExit("style.json: palette index %d" % s)
            return s
        return -1 - self.role(s)

    def spec(self, s):
        if s is None:
            terms = ()
        elif isinstance(s, list):
            terms = tuple(self.term(x) for x in s)
        else:
            terms = (self.term(s),)
        if len(terms) > 3:
            raise SystemExit("style.json: a chain longer than 3: %r" % (s,))
        if terms not in self.spec_ix:
            self.spec_ix[terms] = len(self.specs)
            self.specs.append(terms)
        return self.spec_ix[terms]

    def kind_specs(self):
        rows = []
        for k in self.kinds:
            states = self.style["kinds"].get(k)
            row = []
            for st in self.states:
                triple = None if states is None else states.get(st)
                if triple is None:
                    row.append(None)
                else:
                    row.append(tuple(self.spec(x) for x in triple))
            rows.append(row)
        return rows

    def metrics(self):
        out = []
        for k in self.kinds:
            slots = self.style["metrics"].get(k)
            out.append(None if slots is None else list(slots.values()))
        return out


def generate(style, d=DIR):
    t = Tables(style)
    t.dir = d
    nslot = max(len(v) for v in style["metrics"].values())
    rows, mets = t.kind_specs(), t.metrics()
    h = []
    h.append("// GENERATED by tools/gen_ui_tables.py from style.json.")
    h.append("// Do not edit: change the data and regenerate "
             "(tests/test_ui_tables.py).")
    h.append("#ifndef MOY_UI_TABLES_H\n#define MOY_UI_TABLES_H\n")
    h.append("#include <stdint.h>\n")
    h.append("#define MOY_UI_TOKENS %d" % len(t.tokens))
    h.append("#define MOY_UI_ROLES %d" % len(t.roles))
    h.append("#define MOY_UI_STATES %d" % len(t.states))
    h.append("#define MOY_UI_KINDS %d" % len(t.kinds))
    h.append("#define MOY_UI_COLOR_KINDS %d" % len(style["kinds"]))
    h.append("#define MOY_UI_SLOTS %d" % nslot)
    h.append("#define MOY_UI_SPECS %d" % len(t.specs))
    h.append("#define MOY_UI_HITS_CAP %d" % style["hits_capacity"])
    h.append("#define MOY_UI_GLYPHS %d" % len(style["glyphs"]))
    h.append("#define MOY_UI_GLYPH_SIZE %d" % style["glyph_size"])
    h.append("")
    h.append("// The tokens, in the row's order.")
    h.append("enum {")
    for i, tok in enumerate(t.tokens):
        h.append("    MOY_UI_T_%s = %d," % (_ident(tok), i))
    h.append("};\n")
    h.append("// The states, strongest first (widget_state's precedence).")
    h.append("enum {")
    for i, st in enumerate(t.states):
        h.append("    MOY_UI_%s = %d," % (_ident(st), i))
    h.append("};\n")
    h.append("// The kinds: those a style entry colours, then those with only "
             "metrics.")
    h.append("enum {")
    for i, k in enumerate(t.kinds):
        h.append("    MOY_UI_K_%s = %d," % (_ident(k), i))
    h.append("};\n")
    h.append("// Each kind's metric slots.")
    h.append("enum {")
    for k, slots in style["metrics"].items():
        for i, s in enumerate(slots):
            h.append("    MOY_UI_M_%s_%s = %d," % (_ident(k), _ident(s), i))
    h.append("};\n")
    h.append("typedef struct { int8_t n; int8_t t[3]; } moy_ui_spec_t;")
    h.append("extern const int moy_ui_n_tokens, moy_ui_n_roles, moy_ui_n_states, "
             "moy_ui_n_kinds,")
    h.append("    moy_ui_n_color_kinds, moy_ui_n_glyphs;")
    h.append("extern const int moy_ui_hits_cap;")
    h.append("extern const char *const moy_ui_token_names[MOY_UI_TOKENS];")
    h.append("extern const char *const moy_ui_role_names[MOY_UI_ROLES];")
    h.append("extern const int8_t moy_ui_alias[MOY_UI_ROLES - MOY_UI_TOKENS][3];")
    h.append("extern const char *const moy_ui_state_names[MOY_UI_STATES];")
    h.append("extern const char *const moy_ui_kind_names[MOY_UI_KINDS];")
    h.append("extern const char *const moy_ui_button_kinds[%d][2];"
             % len(style["button_kinds"]))
    h.append("#define MOY_UI_BUTTON_KINDS %d" % len(style["button_kinds"]))
    h.append("extern const moy_ui_spec_t moy_ui_specs[MOY_UI_SPECS];")
    h.append("// [kind][state][field, ink, edge]: a spec index, or 0xff "
             "where the kind names no such state.")
    h.append("extern const uint8_t moy_ui_kind_specs[MOY_UI_KINDS]"
             "[MOY_UI_STATES][3];")
    h.append("// [kind]: the slot count (0: no metrics), then the values.")
    h.append("extern const uint8_t moy_ui_metric_n[MOY_UI_KINDS];")
    h.append("extern const int16_t moy_ui_metric_vals[MOY_UI_KINDS][MOY_UI_SLOTS];")
    h.append("extern const char *const moy_ui_metric_slots[MOY_UI_KINDS];")
    h.append("// The glyph vocabulary: each glyph's rows, bit (size - 1 - col) the ink.")
    h.append("extern const char *const moy_ui_glyph_names[MOY_UI_GLYPHS];")
    h.append("extern const uint16_t moy_ui_glyph_rows[MOY_UI_GLYPHS][MOY_UI_GLYPH_SIZE];")
    h.append("\n#endif // MOY_UI_TABLES_H")

    if len(t.specs) >= 255:
        raise SystemExit("more than 255 distinct token specs")
    c = []
    c.append("// GENERATED by tools/gen_ui_tables.py from style.json.")
    c.append("// Do not edit: change the data and regenerate "
             "(tests/test_ui_tables.py).\n")
    c.append('#include "moy_ui_tables.h"\n')
    c.append("// The counts, for a binding that reads the tables by symbol.")
    for k in ("tokens", "roles", "states", "kinds", "color_kinds", "glyphs"):
        c.append("const int moy_ui_n_%s = MOY_UI_%s;" % (k, k.upper()))
    c.append("const int moy_ui_hits_cap = MOY_UI_HITS_CAP;")
    c.append("")

    def names(decl, seq):
        c.append("%s = {" % decl)
        for s in seq:
            c.append("    %s," % _c_str(s))
        c.append("};\n")

    names("const char *const moy_ui_token_names[MOY_UI_TOKENS]", t.tokens)
    names("const char *const moy_ui_role_names[MOY_UI_ROLES]", t.roles)
    c.append("const int8_t moy_ui_alias[MOY_UI_ROLES - MOY_UI_TOKENS][3] = {")
    for a in t.aliases:
        chain = [t.tokens.index(x) for x in style["aliases"][a]]
        if len(chain) > 3 or any(x not in t.tokens for x in style["aliases"][a]):
            raise SystemExit("alias %s: a chain of tokens, at most 3" % a)
        chain += [-1] * (3 - len(chain))
        c.append("    {%s},  // %s" % (", ".join(map(str, chain)), a))
    c.append("};\n")
    names("const char *const moy_ui_state_names[MOY_UI_STATES]", t.states)
    names("const char *const moy_ui_kind_names[MOY_UI_KINDS]", t.kinds)
    c.append("const char *const moy_ui_button_kinds[%d][2] = {"
             % len(style["button_kinds"]))
    for k, v in style["button_kinds"].items():
        c.append("    {%s, %s}," % (_c_str(k), _c_str(v)))
    c.append("};\n")
    c.append("const moy_ui_spec_t moy_ui_specs[MOY_UI_SPECS] = {")
    for terms in t.specs:
        pad = list(terms) + [0] * (3 - len(terms))
        c.append("    {%d, {%s}}," % (len(terms), ", ".join(map(str, pad))))
    c.append("};\n")
    c.append("const uint8_t moy_ui_kind_specs[MOY_UI_KINDS][MOY_UI_STATES][3] = {")
    for k, row in zip(t.kinds, rows):
        cells = ", ".join("{0xff, 0xff, 0xff}" if tr is None else
                          "{%d, %d, %d}" % tr for tr in row)
        c.append("    {%s},  // %s" % (cells, k))
    c.append("};\n")
    c.append("const uint8_t moy_ui_metric_n[MOY_UI_KINDS] = {%s};\n" % ", ".join(
        str(len(style["metrics"].get(k, {}))) for k in t.kinds))
    c.append("const int16_t moy_ui_metric_vals[MOY_UI_KINDS][MOY_UI_SLOTS] = {")
    for k, vals in zip(t.kinds, mets):
        v = (vals or []) + [0] * (nslot - len(vals or []))
        c.append("    {%s},  // %s" % (", ".join(map(str, v)), k))
    c.append("};\n")
    names("const char *const moy_ui_metric_slots[MOY_UI_KINDS]",
          [" ".join(style["metrics"].get(k, {})) for k in t.kinds])
    gs = style["glyph_size"]
    if gs > 16:
        raise SystemExit("a glyph row is a uint16: glyph_size %d" % gs)
    names("const char *const moy_ui_glyph_names[MOY_UI_GLYPHS]", list(style["glyphs"]))
    c.append("const uint16_t moy_ui_glyph_rows[MOY_UI_GLYPHS][MOY_UI_GLYPH_SIZE] = {")
    for k, rows in style["glyphs"].items():
        if len(rows) != gs or any(len(r) != gs or set(r) - set("#.") for r in rows):
            raise SystemExit("glyph %s: %d rows of %d '#'/'.'" % (k, gs, gs))
        vals = [sum(1 << (gs - 1 - i) for i, ch in enumerate(r) if ch == "#")
                for r in rows]
        c.append("    {%s},  // %s" % (", ".join("0x%03X" % v for v in vals), k))
    c.append("};\n")
    th, tc = generate_theme(style, t)
    h[-1:-1] = th
    c.extend(tc)
    return "\n".join(h) + "\n", "\n".join(c)


def _luminance():
    """MOY64's relative luminance (WCAG), x10000, from runtime/palette.py."""
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        "_moy64", os.path.join(ROOT, "runtime", "palette.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)

    def lin(v):
        v /= 255.0
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    return [round(10000 * (0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)))
            for r, g, b in mod.MOY64]


def generate_theme(style, t):
    """The theme loader's tables (native/moy_ui/moy_theme.c): format 1's
    limits, the derivation rules, the readability pairs, MOY64's luminance and
    the seed packages' bytes."""
    th = style["theme"]
    seeds = []
    for name in th["seeds"]:
        with open(os.path.join(t.dir, "themes", name + ".json"), "rb") as f:
            src = f.read()
        pkg = json.loads(src)
        if pkg.get("name") != name or len(src) > th["bytes"]:
            raise SystemExit("themes/%s.json: named %s, within %d bytes"
                             % (name, name, th["bytes"]))
        seeds.append((name, src))
    root_pkg = json.loads(seeds[0][1])
    root = root_pkg["colors"]
    roles = t.tokens + list(th["content"])
    if set(roles) & set(t.aliases) or len(set(roles)) != len(roles):
        raise SystemExit("theme.content: a role named twice")
    metrics = list(th["metrics"])
    missing = [m for m in metrics if m not in root_pkg.get("metrics", {})]
    if missing:
        raise SystemExit("the default theme leaves metrics %s unset" % missing)
    rules, at, flags = [], [], [0] * len(roles)
    for v in ("dark", "light", "both"):
        at.append((len(rules), len(th["derive"][v])))
        for role, val in th["derive"][v]:
            r = roles.index(role)
            if isinstance(val, bool):
                flags[r] = 1
                rules.append((r, 0, int(val)))
            elif isinstance(val, int):
                rules.append((r, 0, val))
            else:
                rules.append((r, 1, roles.index(val)))
    derived = {roles[r] for r, _k, _v in rules}
    for v in ("dark", "light"):
        missing = [k for k in roles if k not in derived and k not in root[v]]
        if missing:
            raise SystemExit("the default theme's %s leaves %s unset" % (v, missing))
    parts = t.kinds + list(th["parts"])
    states = t.states + list(th["states"])
    if len(set(parts)) != len(parts) or len(set(states)) != len(states):
        raise SystemExit("theme.parts / theme.states: a name twice")
    nxt = []
    for st in states:
        if st == "rest":
            nxt.append(255)
            continue
        seen, cur = set(), st
        while cur != "rest":
            if cur in seen or th["chain"].get(cur) not in states:
                raise SystemExit("theme.chain: %s does not end at rest" % st)
            seen.add(cur)
            cur = th["chain"][cur]
        nxt.append(states.index(th["chain"][st]))
    h = ["// Theme packages, format 1 (moy_theme.c): the limits, the derivation",
         "// rules, the readability pairs, MOY64's luminance and the seeds.",
         "#define MOY_THEME_FORMAT %d" % th["format"],
         "#define MOY_THEME_SEEDS %d" % len(seeds),
         "#define MOY_THEME_BYTES %d" % th["bytes"],
         "#define MOY_THEME_DEPTH %d" % th["depth"],
         "#define MOY_THEME_RULES %d" % len(rules),
         "#define MOY_THEME_PAIRS %d" % len(th["pairs"]),
         "#define MOY_THEME_CONTRAST %d" % th["contrast"],
         "#define MOY_THEME_RESERVED %d" % len(th["reserved"]),
         "#define MOY_THEME_ROLES %d  // the tokens, then the content roles" % len(roles),
         "#define MOY_THEME_METRICS %d" % len(metrics),
         "#define MOY_THEME_EFFECTS %d" % len(th["effects"]),
         "#define MOY_THEME_EFFECTS_CAP %d" % th["effects_cap"],
         "// What `text` and `surfaces` are keyed by: the kinds, then the chrome's",
         "// parts; the style's states, then a window's.",
         "#define MOY_THEME_PARTS %d" % len(parts),
         "#define MOY_THEME_STATES %d" % len(states),
         "#define MOY_THEME_EDGES %d" % len(th["edges"]),
         "#define MOY_THEME_FILLS %d" % len(th["fills"]),
         "#define MOY_THEME_SURFACES_CAP %d" % th["surfaces_cap"],
         "#define MOY_THEME_SURFACE_LEN %d" % th["surface_len"],
         "// A frame: its style, its title's alignment, its buttons' letters.",
         "#define MOY_THEME_FRAMES %d" % len(th["frames"]),
         "#define MOY_THEME_ALIGNS %d" % len(th["title_aligns"]),
         "#define MOY_THEME_FRAME_BUTTONS %s" % _c_str(th["frame_buttons"]),
         "enum {",
         *["    MOY_THEME_FRAME_%s = %d," % (_ident(f), i) for i, f in enumerate(th["frames"])],
         "};",
         "enum {",
         *["    MOY_THEME_ALIGN_%s = %d," % (_ident(a), i)
           for i, a in enumerate(th["title_aligns"])],
         "};",
         "enum {",
         *["    MOY_THEME_M_%s = %d," % (_ident(m), i) for i, m in enumerate(metrics)],
         "};",
         "enum {",
         *["    MOY_THEME_FX_%s = %d," % (_ident(e), i) for i, e in enumerate(th["effects"])],
         "};",
         "// The chrome's parts, after the kinds.",
         "enum {",
         *["    MOY_THEME_P_%s = %d," % (_ident(p), len(t.kinds) + i)
           for i, p in enumerate(th["parts"])],
         "};",
         "// The states past the style's.",
         "enum {",
         *["    MOY_THEME_S_%s = %d," % (_ident(st), len(t.states) + i)
           for i, st in enumerate(th["states"])],
         "};",
         "// A missing role's rule: `role` gets `v`, a palette index or flag, or",
         "// (is_role) the role `v`'s value.",
         "typedef struct { uint8_t role, is_role, v; } moy_theme_rule_t;",
         "extern const moy_theme_rule_t moy_theme_rules[MOY_THEME_RULES];",
         "// [dark, light, both]: (first rule, count).",
         "extern const uint8_t moy_theme_rules_at[3][2];",
         "extern const uint8_t moy_theme_flag[MOY_THEME_ROLES];",
         "extern const char *const moy_theme_role_names[MOY_THEME_ROLES];",
         "extern const char *const moy_theme_metric_names[MOY_THEME_METRICS];",
         "// each metric's [min, max]",
         "extern const int8_t moy_theme_metric_range[MOY_THEME_METRICS][2];",
         "extern const char *const moy_theme_effect_names[MOY_THEME_EFFECTS];",
         "extern const char *const moy_theme_part_names[MOY_THEME_PARTS];",
         "extern const char *const moy_theme_state_names[MOY_THEME_STATES];",
         "// The state a state falls back to when a part does not name it; rest: 255.",
         "extern const uint8_t moy_theme_state_next[MOY_THEME_STATES];",
         "extern const char *const moy_theme_edge_names[MOY_THEME_EDGES];",
         "extern const char *const moy_theme_fill_names[MOY_THEME_FILLS];",
         "extern const char *const moy_theme_frame_names[MOY_THEME_FRAMES];",
         "extern const char *const moy_theme_align_names[MOY_THEME_ALIGNS];",
         "extern const uint8_t moy_theme_pairs[MOY_THEME_PAIRS][2];",
         "extern const uint16_t moy_theme_lum[64];",
         "extern const char *const moy_theme_reserved[MOY_THEME_RESERVED];",
         "extern const char *const moy_theme_seed_names[MOY_THEME_SEEDS];",
         "extern const char *const moy_theme_seed_src[MOY_THEME_SEEDS];",
         "extern const uint16_t moy_theme_seed_len[MOY_THEME_SEEDS];",
         "extern const int moy_ui_n_themes, moy_theme_n_roles, moy_theme_n_metrics,",
         "    moy_theme_n_effects, moy_theme_n_parts, moy_theme_n_states;"]
    c = ["const moy_theme_rule_t moy_theme_rules[MOY_THEME_RULES] = {"]
    for r, k, v in rules:
        c.append("    {%d, %d, %d},  // %s" % (r, k, v, roles[r]))
    c.append("};\n")
    c.append("const uint8_t moy_theme_rules_at[3][2] = {%s};\n"
             % ", ".join("{%d, %d}" % a for a in at))
    c.append("const uint8_t moy_theme_flag[MOY_THEME_ROLES] = {%s};\n"
             % ", ".join(map(str, flags)))
    c.append("const char *const moy_theme_role_names[MOY_THEME_ROLES] = {")
    c.extend("    %s," % _c_str(r) for r in roles)
    c.append("};\n")
    c.append("const char *const moy_theme_metric_names[MOY_THEME_METRICS] = {")
    c.extend("    %s," % _c_str(m) for m in metrics)
    c.append("};\n")
    c.append("const int8_t moy_theme_metric_range[MOY_THEME_METRICS][2] = {%s};\n"
             % ", ".join("{%d, %d}" % tuple(th["metrics"][m]) for m in metrics))
    c.append("const char *const moy_theme_effect_names[MOY_THEME_EFFECTS] = {")
    c.extend("    %s," % _c_str(e) for e in th["effects"])
    c.append("};\n")
    for decl, seq in (("moy_theme_part_names[MOY_THEME_PARTS]", parts),
                      ("moy_theme_state_names[MOY_THEME_STATES]", states),
                      ("moy_theme_edge_names[MOY_THEME_EDGES]", th["edges"]),
                      ("moy_theme_fill_names[MOY_THEME_FILLS]", th["fills"]),
                      ("moy_theme_frame_names[MOY_THEME_FRAMES]", th["frames"]),
                      ("moy_theme_align_names[MOY_THEME_ALIGNS]", th["title_aligns"])):
        c.append("const char *const %s = {" % decl)
        c.extend("    %s," % _c_str(n) for n in seq)
        c.append("};\n")
    c.append("const uint8_t moy_theme_state_next[MOY_THEME_STATES] = {%s};\n"
             % ", ".join(map(str, nxt)))
    c.append("const uint8_t moy_theme_pairs[MOY_THEME_PAIRS][2] = {")
    for a, b in th["pairs"]:
        c.append("    {%d, %d},  // %s / %s" % (roles.index(a), roles.index(b), a, b))
    c.append("};\n")
    lum = _luminance()
    c.append("const uint16_t moy_theme_lum[64] = {")
    for i in range(0, 64, 8):
        c.append("    %s," % ", ".join("%5d" % v for v in lum[i:i + 8]))
    c.append("};\n")
    c.append("const char *const moy_theme_reserved[MOY_THEME_RESERVED] = {")
    c.extend("    %s," % _c_str(k) for k in th["reserved"])
    c.append("};\n")
    c.append("const char *const moy_theme_seed_names[MOY_THEME_SEEDS] = {")
    c.extend("    %s," % _c_str(n) for n, _s in seeds)
    c.append("};\n")
    c.append("const char *const moy_theme_seed_src[MOY_THEME_SEEDS] = {")
    for n, src in seeds:
        lines = src.decode("utf-8").splitlines(True)
        c.append("    // themes/%s.json" % n)
        c.extend("    %s" % _c_str(ln) for ln in lines[:-1])
        c.append("    %s," % _c_str(lines[-1]))
    c.append("};\n")
    c.append("const int moy_ui_n_themes = MOY_THEME_SEEDS;")
    c.append("const int moy_theme_n_roles = MOY_THEME_ROLES;")
    c.append("const int moy_theme_n_metrics = MOY_THEME_METRICS;")
    c.append("const int moy_theme_n_effects = MOY_THEME_EFFECTS;")
    c.append("const int moy_theme_n_parts = MOY_THEME_PARTS;")
    c.append("const int moy_theme_n_states = MOY_THEME_STATES;")
    c.append("const uint16_t moy_theme_seed_len[MOY_THEME_SEEDS] = {%s};\n"
             % ", ".join(str(len(s)) for _n, s in seeds))
    return h, c


def generate_strings(strings):
    """moy_str_table.h/.c: the ids, their names and English."""
    ids = list(strings)
    for sid, text in strings.items():
        if not re.match(r"^[a-z_]+\.[a-z_]+$", sid):
            raise SystemExit("%s: a string id is section.name" % sid)
        bad = [m for m in re.findall(r"%(?:08x|.)", text.replace("%%", ""))
               if m not in ("%s", "%d", "%u", "%08x")]
        if bad:
            raise SystemExit("%s: a conversion outside %%s %%d %%u %%08x" % sid)
    head = ("// GENERATED by tools/gen_ui_tables.py from strings/en.json.\n"
            "// Do not edit: change the data and regenerate "
            "(tests/test_ui_tables.py).\n")
    h = [head, "#ifndef MOY_STR_TABLE_H\n#define MOY_STR_TABLE_H\n",
         "#define MOY_STRINGS %d\n" % len(ids), "// The string ids.", "enum {"]
    for i, sid in enumerate(ids):
        h.append("    MOY_S_%s = %d," % (_ident(sid), i))
    h.append("};\n")
    h.append("extern const char *const moy_str_ids[MOY_STRINGS];")
    h.append("extern const char *const moy_str_en[MOY_STRINGS];")
    h.append("\n#endif // MOY_STR_TABLE_H")
    c = [head, '#include "moy_str_table.h"\n']
    for decl, seq in (("moy_str_ids", ids), ("moy_str_en", [strings[i] for i in ids])):
        c.append("const char *const %s[MOY_STRINGS] = {" % decl)
        for s in seq:
            c.append("    %s," % _c_str(s))
        c.append("};\n")
    return "\n".join(h) + "\n", "\n".join(c)


def load(d):
    with open(os.path.join(d, "style.json")) as f:
        return json.load(f)


def load_strings(d):
    with open(os.path.join(d, "strings", "en.json")) as f:
        return json.load(f)["strings"]


def outputs(ui_dir=DIR, str_dir=STR_DIR):
    """[(path, text)] of every generated file."""
    h, c = generate(load(ui_dir), ui_dir)
    sh, sc = generate_strings(load_strings(str_dir))
    return [(os.path.join(ui_dir, "moy_ui_tables.h"), h),
            (os.path.join(ui_dir, "moy_ui_tables.c"), c),
            (os.path.join(str_dir, "moy_str_table.h"), sh),
            (os.path.join(str_dir, "moy_str_table.c"), sc)]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dir", default=DIR)
    ap.add_argument("--str-dir", default=STR_DIR)
    ap.add_argument("--check", action="store_true",
                    help="fail when the committed tables differ")
    a = ap.parse_args(argv)
    out = outputs(a.dir, a.str_dir)
    if a.check:
        for p, text in out:
            if not os.path.exists(p) or open(p).read() != text:
                print("%s is stale: run tools/gen_ui_tables.py" % p)
                return 1
        return 0
    for p, text in out:
        with open(p, "w") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
