"""tools/gen_os_table.py's generator: the call table's source, its rules and
one emitter per tier."""


def header(source, mark):
    """The first line of every file tools/gen_os_table.py writes whole, as a
    `mark` comment ("//", "#", "--"; "" for the bare text): what made it, from
    what, and how to make it again. `--check` fails a file without it, since
    the file then differs from what the generator writes."""
    text = ("GENERATED by tools/gen_os_table.py from %s: do not edit; run tools/gen_os_table.py."
            % source)
    return "%s %s" % (mark, text) if mark else text


class TableError(ValueError):
    """A source the rules refuse, named by its row."""
